import { describe, expect, it } from 'vitest';
import { decide } from '../src/decision.js';

const основа = {
  createdAt: 1000,
  expiresAt: 1900,
  lateWindowSeconds: 86400,
  now: 1500,
};

describe('decide', () => {
  it('подтверждённый платёж в срок — оплачен', () => {
    const р = decide({
      ...основа,
      orderState: 'ожидает',
      status: { status: 'confirmed', signature: 'п1', amountPaid: '32.64' },
    });
    expect(р.action).toBe('оплачен');
  });

  it('платёж не пришёл, срок не вышел — ждать', () => {
    const р = decide({ ...основа, orderState: 'ожидает', status: { status: 'pending' } });
    expect(р.action).toBe('ждать');
  });

  it('платёж не пришёл, срок вышел — просрочен', () => {
    const р = decide({ ...основа, now: 2000, orderState: 'ожидает', status: { status: 'pending' } });
    expect(р.action).toBe('просрочен');
  });

  it('платёж пришёл после срока, в пределах окна — поздний, НЕ отмена', () => {
    const р = decide({
      ...основа,
      now: 5000,
      orderState: 'просрочен',
      status: { status: 'confirmed', signature: 'п2', amountPaid: '32.64' },
    });
    expect(р.action).toBe('поздний');
  });

  it('платёж пришёл далеко за окном — всё равно поздний: продавец должен узнать', () => {
    const р = decide({
      ...основа,
      now: 1000 + 86400 * 3,
      orderState: 'просрочен',
      status: { status: 'confirmed', signature: 'п3', amountPaid: '32.64' },
    });
    expect(р.action).toBe('поздний');
  });

  it('несовпадение суммы не отменяет и не подтверждает', () => {
    const р = decide({
      ...основа,
      now: 5000,
      orderState: 'ожидает',
      status: { status: 'mismatch', signature: 'п4', reason: 'сумма меньше' },
    });
    expect(р.action).toBe('не сошлось');
  });

  it('уже оплаченный заказ не трогаем даже при повторном подтверждении', () => {
    const р = decide({
      ...основа,
      orderState: 'оплачен',
      status: { status: 'confirmed', signature: 'п5', amountPaid: '32.64' },
    });
    expect(р.action).toBe('ждать');
  });

  it('уведомлённый заказ не трогаем', () => {
    const р = decide({
      ...основа,
      orderState: 'уведомлён',
      status: { status: 'confirmed', signature: 'п6', amountPaid: '32.64' },
    });
    expect(р.action).toBe('ждать');
  });

  it('заказ на ручном разборе (ошибка настроек) не трогаем автоматикой', () => {
    // «Не сошлось» сюда больше не годится примером: с задачи 2 финального
    // ревью оно как раз ПРОВЕРЯЕТСЯ автоматикой повторно (см. тесты ниже,
    // «не тупик»). А вот «ошибка настроек» — действительно ждёт только
    // человека: заказ сам по себе не изменится, пока не изменятся
    // настройки сервера (см. `checker.ts`).
    const р = decide({
      ...основа,
      orderState: 'ошибка настроек',
      status: { status: 'confirmed', signature: 'п7', amountPaid: '32.64' },
    });
    expect(р.action).toBe('ждать');
  });

  it('заметка при несовпадении содержит причину и подпись транзакции', () => {
    const р = decide({
      ...основа,
      now: 5000,
      orderState: 'ожидает',
      status: { status: 'mismatch', signature: 'п8', reason: 'сумма меньше' },
    });
    expect(р.note).toContain('п8');
    expect(р.note).toContain('сумма меньше');
  });

  it('статус expired от SDK на невышедшем сроке всё равно даёт ждать', () => {
    const р = decide({ ...основа, orderState: 'ожидает', status: { status: 'expired' } });
    expect(р.action).toBe('ждать');
  });

  it('платёж пришёл ровно на границе: заказ ещё «ожидает», а срок уже вышел — оплачен, не поздний', () => {
    // Правка финального ревью (задача 3): раньше здесь ожидался «поздний»
    // — но это и есть сама находка. Между отправкой платежа покупателем и
    // попаданием транзакции в подтверждённый блок проходит 15–30 секунд, и
    // браузер покупателя знает об этом (продолжает опрашивать статус ещё
    // три минуты после нуля на таймере). Заказ ещё не был официально
    // переведён в «просрочен» — то есть цена по нему ещё действовала, и
    // подтверждённый платёж завершает его как «оплачен» независимо от
    // истечения котировки. «Поздний» наступает только для заказа, уже
    // переведённого в «просрочен» (см. следующий тест).
    const р = decide({
      ...основа,
      now: 2000,
      orderState: 'ожидает',
      status: { status: 'confirmed', signature: 'п9', amountPaid: '32.64' },
    });
    expect(р.action).toBe('оплачен');
  });

  it('«не сошлось» — не тупик: заказ снова проверяется, и подтверждённый платёж завершает его', () => {
    // Находка финального ревью (задача 2): первой транзакцией по метке
    // мог оказаться протухший повтор кошелька или чужая дешёвая
    // транзакция — «не сошлось» не должно быть терминальным состоянием,
    // из которого заказ больше никогда не проверяется.
    const р = decide({
      ...основа,
      orderState: 'не сошлось',
      status: { status: 'confirmed', signature: 'п11', amountPaid: '32.64' },
    });
    expect(р.action).toBe('оплачен');
  });

  it('«не сошлось» с повторным расхождением остаётся «не сошлось», а не проваливается в чёрный список', () => {
    const р = decide({
      ...основа,
      orderState: 'не сошлось',
      status: { status: 'mismatch', signature: 'п12', reason: 'сумма меньше' },
    });
    expect(р.action).toBe('не сошлось');
  });

  it('заказ с поздним платежом не трогаем: решение по нему уже принято человеком', () => {
    // «Поздний» отличается от остальных закрытых состояний тем, что по нему
    // на каждой проверке снова приходит status: 'confirmed' — платёж
    // действительно существует. Если белый список когда-нибудь тронут,
    // именно это состояние первым провалится обратно в общую логику и
    // будет переподтверждено повторно.
    const р = decide({
      ...основа,
      orderState: 'поздний',
      status: { status: 'confirmed', signature: 'п10', amountPaid: '32.64' },
    });
    expect(р.action).toBe('ждать');
  });
});
