// Правка ревью (задача 8): `Cache-Control: no-store` на странице списка
// заказов не гарантирует, что браузер не восстановит её из своего
// back/forward cache (bfcache) по кнопке «Назад» — воспроизведено в
// настоящем Chrome: вход → список → «Выйти» → «Назад» вернул список без
// единого сетевого запроса к серверу, несмотря на заголовок. Стандартное
// лекарство — `pageshow` с `event.persisted`: этот признак означает, что
// страница показана ИЗ КЕША, а не загружена заново, и тогда её нужно
// безусловно перезагрузить — сервер снова проверит куку (уже отозванную
// выходом — см. `routes-admin.ts`, поколение сессий) и либо покажет
// актуальный список, либо перенаправит на вход.
//
// Внешний файл, а не встроенный <script>: страница отдаётся с
// Content-Security-Policy: default-src 'self' без 'unsafe-inline', и
// встроенный скрипт этой политикой браузер молча не исполнил бы вовсе (тот
// же урок, что и в public/checkout.js).
(function () {
    'use strict';

    window.addEventListener('pageshow', function (event) {
        if (event.persisted) {
            location.reload();
        }
    });
})();
