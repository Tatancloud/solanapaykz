/**
 * Имитатор Tilda для сквозной проверки всего пути (задача 9): оформляет
 * заказ настоящим подписанным POST-запросом на наш `/tilda/pay`, поднимает
 * свой HTTP-слушатель для приёма нашего уведомления об оплате и умеет
 * отвечать на него `OK`, мусором или не отвечать вовсе.
 *
 * ГЛАВНОЕ УСЛОВИЕ ЭТОГО ФАЙЛА: подпись здесь считается СВОЕЙ, независимой
 * реализацией HMAC-SHA-256 — по описанию протокола (см. `docs/tilda-protokol.md`,
 * раздел «Подпись», и правило составления строки для подписи из плана
 * задачи 2: `{{order_id}}|{{amount}}|{{currency}}|{{timestamp}}|{{test_mode}}`,
 * HMAC-SHA-256, секрет как ключ, нижний регистр hex), а НЕ вызовом
 * `signFields`/`verifySignature` из `../src/signature.ts`.
 *
 * Почему это важно: проверка нашей подписи нашим же кодом доказывает только
 * то, что реализация согласована сама с собой — если бы `signFields` считал
 * подпись неверно (скажем, не в том порядке полей), тест, который её же
 * использует для проверки, никогда бы этого не заметил. Настоящая Tilda
 * реализует протокол независимо от нашего кода — по документации; имитатор
 * должен делать ровно то же самое, чтобы тест что-то доказывал.
 *
 * `crypto.createHmac`/`crypto.timingSafeEqual` — единственное, что этот файл
 * берёт из платформы, не из нашего проекта.
 */
import { createHmac, randomBytes, timingSafeEqual } from 'node:crypto';
import http from 'node:http';
import type { AddressInfo } from 'node:net';

/** Поля, входящие в подпись, и их порядок — из протокола (см. заголовок файла), не импортированы из кода сервера. */
const ПОЛЯ_ПОДПИСИ = ['order_id', 'amount', 'currency', 'timestamp', 'test_mode'] as const;

function строкаДляПодписи(поля: Record<string, string>): string {
  return ПОЛЯ_ПОДПИСИ.map((имя) => поля[имя] ?? '').join('|');
}

/** HMAC-SHA-256 в нижнем регистре hex — независимая реализация по описанию протокола. */
function подписать(поля: Record<string, string>, секрет: string): string {
  return createHmac('sha256', секрет).update(строкаДляПодписи(поля), 'utf8').digest('hex');
}

/** Сравнение постоянного времени — тем же приёмом, что задание требует и от самого сервера. */
function совпадаетСПодписью(поля: Record<string, string>, подпись: string, секрет: string): boolean {
  const ожидаемая = подписать(поля, секрет);
  const пришедшая = подпись.trim().toLowerCase();
  const а = Buffer.from(пришедшая, 'utf8');
  const б = Buffer.from(ожидаемая, 'utf8');
  if (а.length !== б.length) return false;
  return timingSafeEqual(а, б);
}

export type РежимОтвета = 'OK' | 'мусор' | 'без ответа';

export interface ОпцииЗаказа {
  /** Сумма в тенге, как её укажет покупатель Tilda. */
  amount: string;
  /** Номер заказа Tilda — по умолчанию случайный вида «<проект>:имитатор-N-hex». */
  orderId?: string;
  currency?: string;
  testMode?: boolean;
}

export interface РезультатОформления {
  status: number;
  /** Заголовок `Location` из ответа сервера — путь к странице оплаты, если она была выдана. */
  location: string | null;
  /** Ключ страницы оплаты, извлечённый из `Location` (или `null`, если сервер ответил не редиректом на неё). */
  token: string | null;
}

export interface ОпцииИмитатора {
  /**
   * Адрес нашего сервера, например `http://127.0.0.1:12345`. Необязателен
   * при запуске: слушатель уведомлений (`notifyUrl`) не зависит от адреса
   * нашего сервера и поднимается независимо от него — типичный порядок в
   * тестах обратный (сначала поднимается имитатор, чтобы получить
   * `notifyUrl` для настроек сервера, и только потом сам сервер, чей адрес
   * узнаётся уже после запуска). Задать или изменить можно и позже —
   * через `имитатор.адресСервера`.
   */
  адресСервера?: string;
  /** Секрет заказа — тот же, что в `config.orderSecret` нашего сервера: Tilda хранит его как настройку своей стороны интеграции, и имитатор в этой роли делает то же самое. */
  секретЗаказа: string;
  /** Секрет уведомлений — тот же, что в `config.notifySecret`. */
  секретУведомления: string;
  /** Как отвечать на уведомление об оплате. По умолчанию `'OK'`; можно менять на лету через `имитатор.отвечать`. */
  отвечать?: РежимОтвета;
}

export interface Имитатор {
  /** Адрес, на который наш сервер должен слать уведомления — подставляется в `config.tildaNotifyUrl` при тестовом запуске сервера. */
  readonly notifyUrl: string;
  /** Адрес нашего сервера — читается и пишется (см. `ОпцииИмитатора.адресСервера`). */
  адресСервера: string;
  /** Как отвечать на СЛЕДУЮЩЕЕ уведомление — читается и пишется, меняется между вызовами без пересоздания имитатора. */
  отвечать: РежимОтвета;
  /** Все уведомления, дошедшие до имитатора, в порядке получения. */
  readonly полученныеУведомления: Array<Record<string, string>>;
  /** Оформляет заказ: шлёт независимо подписанный POST на `/tilda/pay` нашего сервера — как это сделала бы настоящая Tilda, перенаправляя покупателя из его браузера. */
  оформитьЗаказ(опции: ОпцииЗаказа): Promise<РезультатОформления>;
  /** Проверяет подпись уведомления СВОЕЙ реализацией (см. заголовок файла) — не переиспользует `verifySignature` сервера. */
  подписьВерна(поля: Record<string, string>): boolean;
  /** Останавливает слушатель имитатора. */
  остановить(): Promise<void>;
}

let счётчикЗаказов = 0;

export async function запуститьИмитатор(опции: ОпцииИмитатора): Promise<Имитатор> {
  const полученныеУведомления: Array<Record<string, string>> = [];
  let текущийРежим: РежимОтвета = опции.отвечать ?? 'OK';

  const сервер = http.createServer((req, res) => {
    if (текущийРежим === 'без ответа') {
      // Специально ничего не отвечаем и не закрываем соединение — имитация
      // недоступной или зависшей стороны Tilda. Отправитель уведомления
      // (`notifyTilda`, см. `src/tilda/notify.ts`) сам отвалится по своему
      // тайм-ауту запроса (10 секунд) — здесь ничего искусственно
      // ускорять не нужно.
      return;
    }

    const части: Buffer[] = [];
    req.on('data', (кусок: Buffer) => части.push(кусок));
    req.on('end', () => {
      const тело = Buffer.concat(части).toString('utf8');
      const поля: Record<string, string> = {};
      for (const [ключ, значение] of new URLSearchParams(тело)) {
        поля[ключ] = значение;
      }
      полученныеУведомления.push(поля);

      if (текущийРежим === 'OK') {
        res.writeHead(200, { 'content-type': 'text/plain; charset=utf-8' });
        res.end('OK');
      } else {
        // 'мусор' — код 200, но тело не «OK». Ровно так в этом проекте уже
        // путали «отправлено» с «доставлено» (см. заголовок
        // `src/tilda/notify.ts`) — сервер обязан не засчитывать такой ответ
        // успехом, а имитатор проверяет именно это поведение.
        res.writeHead(200, { 'content-type': 'text/plain; charset=utf-8' });
        res.end('какой-то мусор, не OK');
      }
    });
  });

  await new Promise<void>((resolve) => сервер.listen(0, '127.0.0.1', resolve));
  const адрес = сервер.address() as AddressInfo;
  const notifyUrl = `http://127.0.0.1:${адрес.port}/notify`;

  // Обычная переменная, а не поле опций: адрес нашего сервера в тестах
  // становится известен только ПОСЛЕ того, как сервер поднят на случайном
  // порту — то есть уже после запуска имитатора (см. `ОпцииИмитатора.адресСервера`).
  // Присваивание `имитатор.адресСервера = ...` (через геттер/сеттор ниже)
  // должно быть видно замыканию `оформитьЗаказ`, которое вызовут позже.
  let адресСервера = опции.адресСервера ?? '';

  async function оформитьЗаказ(заказ: ОпцииЗаказа): Promise<РезультатОформления> {
    if (!адресСервера) {
      throw new Error('Имитатор не знает адрес сервера — задайте имитатор.адресСервера перед оформитьЗаказ()');
    }
    счётчикЗаказов += 1;
    const orderId = заказ.orderId ?? `10868059:имитатор-${счётчикЗаказов}-${randomBytes(4).toString('hex')}`;
    const подписываемыеПоля: Record<string, string> = {
      order_id: orderId,
      amount: заказ.amount,
      currency: заказ.currency ?? 'KZT',
      timestamp: String(Math.floor(Date.now() / 1000)),
      test_mode: заказ.testMode ? '1' : '0',
    };
    const тело = { ...подписываемыеПоля, signature: подписать(подписываемыеПоля, опции.секретЗаказа) };

    const ответ = await fetch(`${адресСервера}/tilda/pay`, {
      method: 'POST',
      redirect: 'manual',
      headers: { 'content-type': 'application/x-www-form-urlencoded' },
      body: new URLSearchParams(тело).toString(),
    });

    const location = ответ.headers.get('location');
    const совпадение = location ? /^\/pay\/([0-9a-f]{32})$/.exec(location) : null;

    return { status: ответ.status, location, token: совпадение ? совпадение[1]! : null };
  }

  function подписьВерна(поля: Record<string, string>): boolean {
    return совпадаетСПодписью(поля, поля.signature ?? '', опции.секретУведомления);
  }

  async function остановить(): Promise<void> {
    await new Promise<void>((resolve) => сервер.close(() => resolve()));
  }

  return {
    notifyUrl,
    get адресСервера(): string {
      return адресСервера;
    },
    set адресСервера(значение: string) {
      адресСервера = значение;
    },
    get отвечать(): РежимОтвета {
      return текущийРежим;
    },
    set отвечать(значение: РежимОтвета) {
      текущийРежим = значение;
    },
    полученныеУведомления,
    оформитьЗаказ,
    подписьВерна,
    остановить,
  };
}
