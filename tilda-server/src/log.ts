/**
 * Журнал сервера: одна строка JSON на запись в stdout.
 *
 * Секрет может утечь тремя разными путями, и у каждого — свой барьер:
 *
 * 1. По имени поля (`secret`, `password`, `pass`, `orderSecret`,
 *    `notifySecret`, `adminPassword`, ...) — дёшево, ловит основной случай,
 *    но ничего не знает о значении и потому бессильно перед адресом узла
 *    Solana (поле `rpcUrl` не похоже ни на «secret», ни на «password», а
 *    несёт ключ провайдера в query-строке) и перед секретом, попавшим в
 *    текст сообщения через интерполяцию (`` `не вышло: ${orderSecret}` ``).
 * 2. Любая строка, похожая на адрес (в поле, во вложенном объекте, в
 *    массиве, в тексте сообщения) — прогоняется через `redactUrl`
 *    независимо от имени поля.
 * 3. Журнал знает сами значения секретов настроек и вырезает их из готовой
 *    строки где угодно — единственный слой, переживающий интерполяцию в
 *    текст.
 *
 * Ни один слой не заменяет остальные: (1) ловит случай, когда секрет
 * попал в лог, а его значение журналу не передали; (3) ловит случай, когда
 * секрет спрятан не под секретным именем поля.
 */

// Сверяем не точное имя поля, а вхождение подстроки без учёта регистра:
// список имён из задания («secret», «password», «pass», «orderSecret»,
// «notifySecret») не покрывает `adminPassword` буквально, а он обязан
// вырезаться — поэтому правило шире, чем перечисление точных имён.
const ПОДСТРОКИ_СЕКРЕТОВ = ['secret', 'password', 'pass'];
const ЗАМЕНА_ПОЛЯ = '[скрыто]';
const ЗАМЕНА_СЕКРЕТА = '<скрыто>';

// Тот же порог, что у проверки настроек (config.ts): секрет короче него —
// не секрет, а вырезание короткой строки (например, из одного символа)
// изувечит весь остальной текст записи.
const МИНИМАЛЬНАЯ_ДЛИНА_СЕКРЕТА_ДЛЯ_ВЫРЕЗАНИЯ = 8;

// Адрес — это то, что не содержит пробелов после «https://»: годится и для
// строкового значения поля целиком, и для вхождения внутри произвольного
// текста сообщения.
const ШАБЛОН_URL = /https?:\/\/\S+/g;

function этоИмяСекрета(ключ: string): boolean {
  const нижний = ключ.toLowerCase();
  return ПОДСТРОКИ_СЕКРЕТОВ.some((подстрока) => нижний.includes(подстрока));
}

export type Поля = Record<string, unknown>;

export interface Log {
  info(msg: string, fields?: Поля): void;
  warn(msg: string, fields?: Поля): void;
  error(msg: string, fields?: Поля): void;
}

/** Оставляет от URL только схему и хост; на нераспознанном вводе не пробрасывает мусор дальше. */
export function redactUrl(url: string): string {
  try {
    const u = new URL(url);
    return `${u.protocol}//${u.host}`;
  } catch {
    return '<адрес скрыт>';
  }
}

/** Заменяет в произвольном тексте все вхождения, похожие на URL, на «схема+хост». */
function вырезатьАдресаВТексте(текст: string): string {
  return текст.replace(ШАБЛОН_URL, (совпадение) => redactUrl(совпадение));
}

function редактироватьЗначение(значение: unknown): unknown {
  if (typeof значение === 'string') {
    return вырезатьАдресаВТексте(значение);
  }
  if (Array.isArray(значение)) {
    return значение.map(редактироватьЗначение);
  }
  if (значение !== null && typeof значение === 'object') {
    return редактироватьПоля(значение as Поля);
  }
  return значение;
}

function редактироватьПоля(поля: Поля): Поля {
  const результат: Поля = {};
  for (const [ключ, значение] of Object.entries(поля)) {
    результат[ключ] = этоИмяСекрета(ключ) ? ЗАМЕНА_ПОЛЯ : редактироватьЗначение(значение);
  }
  return результат;
}

/** Заменяет в готовой строке журнала все вхождения известных значений секретов. */
function вырезатьИзвестныеСекреты(строка: string, секреты: readonly string[]): string {
  let результат = строка;
  for (const секрет of секреты) {
    результат = результат.split(секрет).join(ЗАМЕНА_СЕКРЕТА);
  }
  return результат;
}

/**
 * Создаёт журнал, пишущий через переданную функцию (`sink`) — это позволяет
 * в тестах перехватывать строки вместо реального stdout.
 *
 * `секреты` — известные значения секретов настроек (orderSecret,
 * notifySecret, adminPassword, smtp.pass и т.п.). Короче порога
 * (`МИНИМАЛЬНАЯ_ДЛИНА_СЕКРЕТА_ДЛЯ_ВЫРЕЗАНИЯ`) отбрасываются: слишком
 * короткая строка совпадёт где угодно и изуродует безобидный текст.
 */
export function createLog(sink: (line: string) => void, секреты: readonly string[] = []): Log {
  const известныеСекреты = секреты.filter(
    (с) => [...с].length >= МИНИМАЛЬНАЯ_ДЛИНА_СЕКРЕТА_ДЛЯ_ВЫРЕЗАНИЯ,
  );

  function записать(level: 'info' | 'warn' | 'error', msg: string, fields?: Поля): void {
    const запись = {
      ts: new Date().toISOString(),
      level,
      msg: вырезатьАдресаВТексте(msg),
      ...(fields ? редактироватьПоля(fields) : {}),
    };
    const строка = вырезатьИзвестныеСекреты(JSON.stringify(запись), известныеСекреты);
    sink(строка);
  }

  return {
    info: (msg, fields) => записать('info', msg, fields),
    warn: (msg, fields) => записать('warn', msg, fields),
    error: (msg, fields) => записать('error', msg, fields),
  };
}

/** Журнал по умолчанию — пишет в реальный stdout процесса, без известных секретов. */
export const log: Log = createLog((line) => {
  process.stdout.write(line + '\n');
});
