import type { PaymentStatus } from '@solanapaykz/core';
import type { OrderState } from './db.js';

export interface DecideParams {
  status: PaymentStatus;
  orderState: OrderState;
  expiresAt: number;
  createdAt: number;
  lateWindowSeconds: number;
  now: number;
}

export type Decision =
  | { action: 'ждать'; note: string }
  | { action: 'оплачен'; signature: string; note: string }
  | { action: 'просрочен'; note: string }
  | { action: 'не сошлось'; signature: string; reason: string; note: string }
  | { action: 'поздний'; signature: string; note: string };

export function decide({
  status,
  orderState,
  expiresAt,
  createdAt,
  lateWindowSeconds,
  now,
}: DecideParams): Decision {
  const ждать = (почему: string): Decision => ({ action: 'ждать', note: почему });

  // Белый список, а не чёрный: неучтённое состояние не должно провалиться
  // в общую логику и оказаться отменённым или завершённым. «Не сошлось»
  // тоже в списке (правка финального ревью, задача 2) — раньше это
  // состояние было терминальным по первому же расхождению, хотя причиной
  // могла быть чужая транзакция по той же метке или узел, ещё не
  // раздавший тело транзакции: перепроверка на следующем опросе или
  // проходе обхода может увидеть тот же платёж иначе и всё же подтвердить
  // заказ (см. `checker.ts`, `применитьРешение`, случай «не сошлось»).
  if (orderState !== 'ожидает' && orderState !== 'просрочен' && orderState !== 'не сошлось') {
    return ждать(`Заказ в состоянии «${orderState}» — автоматика его не трогает.`);
  }

  if (status.status === 'confirmed') {
    // Правка финального ревью (задача 3): раньше сравнивался с истечением
    // МОМЕНТ ОБНАРУЖЕНИЯ транзакции, а не момент, когда её отправил
    // покупатель. Между отправкой и попаданием в подтверждённый блок
    // проходит 15–30 секунд, и покупатель, заплативший за секунды до
    // конца срока, попадал в «поздний» уже после истечения — хотя платил
    // ровно вовремя. Теперь заказ, ещё остающийся «ожидает» (или ранее
    // помеченный «не сошлось», но так и не переведённый в «просрочен»),
    // завершается подтверждённым платежом независимо от истечения
    // котировки: раз заказ не был официально закрыт как просроченный,
    // цена по нему ещё действовала на всём его протяжении. «Поздний»
    // остаётся только для заказа, уже переведённого в «просрочен» — то
    // есть отменённого раньше, чем платёж был замечен.
    if (orderState !== 'просрочен') {
      return {
        action: 'оплачен',
        signature: status.signature,
        note: `Платёж получен. Транзакция: ${status.signature}.`,
      };
    }

    // Платёж после того, как заказ уже отменён по истечении цены. Деньги
    // уже у продавца — отменять нельзя ни в пределах окна поздних
    // платежей, ни за ним.
    const заОкном = now - createdAt > lateWindowSeconds;

    return {
      action: 'поздний',
      signature: status.signature,
      note:
        `Платёж получен после истечения цены${заОкном ? ' и за пределами окна поздних платежей' : ''}. ` +
        `Транзакция: ${status.signature}. Проверьте сумму перед отгрузкой.`,
    };
  }

  if (status.status === 'mismatch') {
    // Транзакция есть, но не сходится. Это разбирает человек: автоматика
    // ошибается здесь дороже. Не терминально (см. белый список выше) —
    // заказ останется в выборке обхода (`db.ts`, `listPending`) и будет
    // перепроверен: первой найденной транзакцией по метке может быть
    // провалившаяся попытка кошелька или чужая транзакция, а не платёж
    // покупателя, и следующая проверка может увидеть иначе.
    return {
      action: 'не сошлось',
      signature: status.signature,
      reason: status.reason,
      note:
        `Найдена транзакция ${status.signature}, но она не прошла проверку: ${status.reason}. ` +
        'Проверьте её вручную, прежде чем отгружать заказ.',
    };
  }

  // pending и expired от SDK: о просрочке судим по нашему сроку из записи
  // заказа, а не по чужому вычислению на чужих часах. «Не сошлось» этой
  // веткой не тронуто — оно не переходит в «просрочен» само по себе,
  // только через явное подтверждение или до истечения своего окна в
  // `listPending`.
  if (orderState === 'ожидает' && now > expiresAt) {
    return { action: 'просрочен', note: 'Срок действия цены истёк, платёж не найден.' };
  }

  return ждать('Платёж пока не найден.');
}
