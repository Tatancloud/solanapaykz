/**
 * Наблюдение за поступлениями на кошелёк магазина и опознание платежа по
 * сумме — второй, независимый от метки `reference` путь к тому же заказу
 * (см. спецификацию `process/superpowers/specs/2026-09-17-oplata-po-unikalnoy-summe-design.md`).
 *
 * Зачем он нужен: метку в ссылке Solana Pay проставляют только кошельки,
 * которые эту ссылку читают. Покупатель, чей кошелёк умеет лишь
 * сканировать голый адрес, переводит деньги вручную — и такой платёж
 * `checkPayment` (поиск по метке) не находит никогда. Второй признак, по
 * которому платёж можно узнать без метки, — сумма, уникальная на каждый
 * живой заказ (подбор при создании заказа см. в `db.ts`, `createOrder`).
 *
 * Чего этот модуль НЕ делает: он не решает судьбу заказа. Найдя платёж,
 * он передаёт его `закрытьЗаказ` — и там работает та же дорога, что у
 * платежа по метке (`checker.ts`, `подтвердитьПлатёжПоСумме`): та же
 * блокировка заказа, тот же `decide()`, то же уведомление Tilda и письмо
 * продавцу. Двух разных путей принятия решения об оплате в сервере быть
 * не должно.
 */

import type { Config } from './config.js';
import type { Order, Store } from './db.js';
import type { Log } from './log.js';
import { sendUnmatchedMail, type ОтправкаПисьма } from './mailer.js';
import { поступлениеИзТранзакции, type ПодписьВИстории, type SolanaRpc } from './solana-rpc.js';
import { resolveToken } from '@solanapaykz/core';

/** Интервал обхода поступлений — тот же, что у фоновой проверки заказов. */
const ИНТЕРВАЛ_СКАНИРОВАНИЯ_MS = 60_000;

/**
 * Сколько новых подписей разбираем за один проход.
 *
 * Каждая подпись — это отдельный запрос тела транзакции, то есть прямой
 * расход квоты платного узла. Сто за проход (то есть до ста в минуту) с
 * запасом покрывает поток любого магазина такого размера, а на всплеске
 * (кто-то засыпал кошелёк мелкими переводами) остаток просто уедет в
 * следующий проход: курсор двигается только по разобранному, ничего не
 * теряется.
 */
const ПОТОЛОК_ПОДПИСЕЙ_ЗА_ПРОХОД = 100;

/** Причины, по которым поступление попадает в список неопознанных. */
export const ПРИЧИНЫ = {
  нетЗаказа: 'нет заказа с такой суммой',
  несколькоЗаказов: 'подошло несколько заказов',
  транзакцияСтаршеЗаказа: 'транзакция старше заказа',
  подписьУжеИспользована: 'транзакция уже засчитана другому заказу',
} as const;

export interface ScannerDeps {
  config: Config;
  store: Store;
  rpc: SolanaRpc;
  log: Log;
  /**
   * Закрывает заказ платежом, найденным по сумме. Отдельной функцией, а
   * не прямым обращением к `checker.ts`: сканеру незачем знать, как
   * принимается решение по заказу, а тестам — поднимать половину сервера
   * ради проверки разбора поступлений.
   */
  закрытьЗаказ: (order: Order, signature: string) => Promise<unknown>;
  /** Только для тестов. */
  тест?: {
    потолокПодписейЗаПроход?: number;
    /** Текущее время, Unix-секунды. По умолчанию — настоящие часы. */
    сейчас?: () => number;
    /** Подменяет настоящую отправку письма о неопознанном поступлении. */
    отправкаПисьма?: ОтправкаПисьма;
  };
}

/** Адрес, за которым следим, и mint — если следим за токен-счётом. */
interface Наблюдаемый {
  адрес: string;
  mint?: string;
}

/**
 * За чем следить: для SOL — за самим кошельком магазина, для токена — за
 * его токен-счётом.
 *
 * Перевод токена идёт между токен-счетами, и владелец в списке участников
 * транзакции может не значиться вовсе — следить за его собственным
 * адресом бесполезно. Адрес токен-счёта спрашиваем у узла, а не вычисляем
 * сами: вычисление производного адреса — это криптография (хеш плюс
 * проверка точки на кривой), которой в этом сервере взяться неоткуда и не
 * должно.
 */
async function наблюдаемыйАдрес(deps: ScannerDeps): Promise<Наблюдаемый | null> {
  const { mint } = resolveToken(deps.config.cluster, deps.config.token);
  if (!mint) return { адрес: deps.config.recipient };

  const счета = await deps.rpc.getTokenAccountsByOwner(deps.config.recipient, mint);
  const счёт = счета[0];
  if (счёт === undefined) {
    // Токен-счёта ещё нет — значит этот токен кошельку магазина никто ни
    // разу не присылал. Ждать нечего и следить не за чем; счёт появится
    // с первым же платежом, и тогда следующий проход его найдёт.
    deps.log.info('Токен-счёт магазина ещё не создан — поступлений по этому токену пока не было', {
      token: deps.config.token,
    });
    return null;
  }

  return { адрес: счёт, mint };
}

/**
 * Один проход: читает новые поступления с узла и разбирает их.
 *
 * Правила разбора — спецификация, §6. Главные из них: совпадение суммы
 * только точное, транзакция не старше заказа, одна транзакция закрывает
 * не больше одного заказа. Всё, что не подошло, попадает в список
 * неопознанных — это чужие деньги, уже лежащие на кошельке продавца, и
 * молчать о них нельзя.
 */
export async function сканироватьОдинРаз(deps: ScannerDeps): Promise<void> {
  if (!deps.config.enableAmountMatching) return;

  let наблюдаемый: Наблюдаемый | null;
  try {
    наблюдаемый = await наблюдаемыйАдрес(deps);
  } catch (е) {
    deps.log.warn('Не удалось узнать, за каким счётом следить: узел Solana недоступен или отказал', {
      сообщение: (е as Error).message,
    });
    return;
  }
  if (!наблюдаемый) return;

  const курсор = deps.store.scanCursor();
  const потолок = deps.тест?.потолокПодписейЗаПроход ?? ПОТОЛОК_ПОДПИСЕЙ_ЗА_ПРОХОД;

  let подписи: ПодписьВИстории[];
  try {
    подписи = await deps.rpc.getSignaturesForAddress(наблюдаемый.адрес, {
      limit: потолок,
      ...(курсор ? { until: курсор.signature } : {}),
    });
  } catch (е) {
    // Узел не ответил — это не «поступлений нет». Курсор не двигаем:
    // иначе непрочитанные платежи были бы пропущены навсегда.
    deps.log.warn('Не удалось прочитать поступления: узел Solana недоступен или отказал', {
      сообщение: (е as Error).message,
    });
    return;
  }

  if (подписи.length === 0) return;

  // Первый запуск: запоминаем голову истории и уходим. Разбирать всю
  // прошлую историю кошелька бессмысленно (заказов, которые ждали бы этих
  // платежей, тогда ещё не было) и дорого — тысячи запросов тела
  // транзакции сожгли бы квоту узла в первую же минуту.
  if (!курсор) {
    const голова = подписи[0]!;
    deps.store.setScanCursor({ signature: голова.signature, blockTime: голова.blockTime });
    deps.log.info('Наблюдение за поступлениями начато', {
      счёт: наблюдаемый.адрес,
      сГоловы: голова.signature,
    });
    return;
  }

  // Узел отдаёт от новых к старым — разбираем в обратном порядке, чтобы
  // курсор двигался строго по уже разобранному.
  for (const запись of [...подписи].reverse()) {
    if (запись.err) {
      // Провалившаяся транзакция: денег не было. Пропускаем, но курсор
      // двигаем — возвращаться к ней незачем.
      deps.store.setScanCursor({ signature: запись.signature, blockTime: запись.blockTime });
      continue;
    }

    let tx;
    try {
      tx = await deps.rpc.getTransaction(запись.signature);
    } catch (е) {
      deps.log.warn('Не удалось прочитать транзакцию поступления', {
        signature: запись.signature,
        сообщение: (е as Error).message,
      });
      return;
    }

    if (tx === null) {
      // Подпись в истории уже есть, а тела на нужном уровне подтверждения
      // узел ещё не раздаёт. Уходим, НЕ двигая курсор: вернёмся к этой же
      // подписи следующим проходом.
      return;
    }

    const сумма = поступлениеИзТранзакции(tx, {
      адрес: наблюдаемый.адрес,
      ...(наблюдаемый.mint !== undefined ? { mint: наблюдаемый.mint } : {}),
    });

    if (сумма !== null) {
      await разобратьПоступление(
        { signature: запись.signature, blockTime: запись.blockTime ?? tx.blockTime, amountUnits: сумма },
        deps,
      );
    }

    deps.store.setScanCursor({ signature: запись.signature, blockTime: запись.blockTime });
  }
}

/** Одно поступление: найти заказ или записать его в неопознанные. */
async function разобратьПоступление(
  поступление: { signature: string; blockTime: number | null; amountUnits: string },
  deps: ScannerDeps,
): Promise<void> {
  const сейчас = deps.тест?.сейчас?.() ?? Math.floor(Date.now() / 1000);

  const вНеопознанные = async (причина: string): Promise<void> => {
    const запись = {
      signature: поступление.signature,
      amountUnits: поступление.amountUnits,
      tokenSymbol: deps.config.token,
      blockTime: поступление.blockTime,
      reason: причина,
      seenAt: сейчас,
    };
    deps.store.recordUnmatched(запись);
    deps.log.info('Поступление не опознано', {
      signature: поступление.signature,
      amountUnits: поступление.amountUnits,
      причина,
    });

    // Письмо — оповещение о том, что уже записано и видно в списке
    // заказов: его неудача ничего не меняет и не должна рвать проход.
    // Частоту ограничивает сам `sendUnmatchedMail` (не чаще раза в час).
    try {
      await sendUnmatchedMail(
        { ...запись, mailedAt: null },
        {
          config: deps.config,
          store: deps.store,
          log: deps.log,
          тест: {
            ...(deps.тест?.отправкаПисьма ? { отправка: deps.тест.отправкаПисьма } : {}),
            ...(deps.тест?.сейчас ? { сейчас: deps.тест.сейчас } : {}),
          },
        },
      );
    } catch (е) {
      deps.log.error('Письмо о неопознанном поступлении не отправилось', {
        signature: поступление.signature,
        сообщение: (е as Error).message,
      });
    }
  };

  const кандидаты = deps.store.findLiveOrdersByAmountUnits({
    amountUnits: поступление.amountUnits,
    tokenSymbol: deps.config.token,
    cluster: deps.config.cluster,
    lateWindowSeconds: deps.config.lateWindowSeconds,
    now: сейчас,
  });

  if (кандидаты.length === 0) {
    await вНеопознанные(ПРИЧИНЫ.нетЗаказа);
    return;
  }

  if (кандидаты.length > 1) {
    // Не должно случаться: суммы живых заказов уникальны по построению.
    // Но если случилось — это наша ошибка, и расплачиваться за неё
    // покупателю нельзя: разбирает человек, ни один заказ не закрываем.
    deps.log.error('По одной сумме подошло несколько живых заказов — это ошибка подбора сумм', {
      signature: поступление.signature,
      amountUnits: поступление.amountUnits,
      заказы: кандидаты.map((з) => з.tildaOrderId),
    });
    await вНеопознанные(ПРИЧИНЫ.несколькоЗаказов);
    return;
  }

  const заказ = кандидаты[0]!;

  // Транзакция старше заказа платить по нему не могла. Сумма
  // освобождается, когда заказ закрыт, и может достаться новому заказу —
  // без этой проверки старый платёж по старой странице закрыл бы чужой
  // свежий заказ.
  if (поступление.blockTime !== null && поступление.blockTime < заказ.createdAt) {
    await вНеопознанные(ПРИЧИНЫ.транзакцияСтаршеЗаказа);
    return;
  }

  // Занимаем подпись ДО закрытия заказа: если та же транзакция уже
  // закрыла какой-то заказ, второй раз её засчитывать нельзя.
  if (!deps.store.claimSignature(поступление.signature, заказ.id, сейчас)) {
    await вНеопознанные(ПРИЧИНЫ.подписьУжеИспользована);
    return;
  }

  try {
    await deps.закрытьЗаказ(заказ, поступление.signature);
    deps.log.info('Платёж опознан по сумме', {
      signature: поступление.signature,
      tildaOrderId: заказ.tildaOrderId,
      amountUnits: поступление.amountUnits,
    });
  } catch (е) {
    // Сбой на закрытии (например, не ушло уведомление Tilda) не должен
    // рвать проход: заказ уже помечен оплаченным внутри `закрытьЗаказ`
    // либо не помечен вовсе, а довоз уведомления — забота фонового
    // обхода (`checker.ts`, `довезтиУведомление`). Подпись остаётся
    // занятой: платёж по ней уже сопоставлен этому заказу.
    deps.log.error('Не удалось закрыть заказ платежом, найденным по сумме', {
      signature: поступление.signature,
      tildaOrderId: заказ.tildaOrderId,
      сообщение: (е as Error).message,
    });
  }
}

/**
 * Запускает наблюдение по таймеру. Возвращает функцию остановки — по
 * образцу `startChecker` в `checker.ts`.
 */
export function startScanner(deps: ScannerDeps): () => void {
  const таймер = setInterval(() => {
    void сканироватьОдинРаз(deps).catch((е) => {
      deps.log.error('Проход наблюдения за поступлениями упал целиком', {
        сообщение: (е as Error).message,
      });
    });
  }, ИНТЕРВАЛ_СКАНИРОВАНИЯ_MS);

  таймер.unref?.();

  return () => clearInterval(таймер);
}
