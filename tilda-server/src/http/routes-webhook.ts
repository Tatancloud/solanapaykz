/**
 * `POST /tilda/webhook` — запасной вход: вебхук ОБЫЧНОЙ ФОРМЫ Tilda
 * (Настройки сайта → Формы → Webhook, см. help.tilda.cc/forms/webhook), а
 * НЕ платёжная интеграция задачи 5 (`/tilda/pay`, `tilda/inbound.ts`).
 *
 * Нужен на случай, если интеграция «Новая платёжная система (для
 * разработчиков)» ещё не одобрена Tilda или недоступна продавцу: обычную
 * форму на сайте можно подключить к своему скрипту уже сегодня, без
 * одобрения модератора. Устройство другое, и вот чем именно:
 *
 * - Подписи нет вовсе — у вебхука формы нет понятия секрета заказа, в
 *   отличие от платёжной интеграции (`tilda-protokol.md`, раздел
 *   «Подпись»). Значит заявка приходит НЕПОДПИСАННОЙ: нечем доказать, что
 *   запрос действительно от Tilda, а не от произвольного клиента в
 *   интернете, знающего адрес вебхука. Единственная опора — то, что этот
 *   адрес нигде не публикуется, кроме настроек формы в личном кабинете
 *   Tilda, и то, что поддельная заявка без реальной оплаты по QR так и
 *   останется «ожидает» и никогда не станет «оплачен». Это ограничение, а
 *   не то же самое ручательство, что даёт HMAC-подпись основного входа —
 *   см. `README.md`, раздел «Ограничения запасного входа».
 * - Поля стандартных полей формы Tilda приходят С ЗАГЛАВНОЙ БУКВЫ (`Email`,
 *   `Name`, `Phone`) — не путать со строчными полями платёжной интеграции
 *   (`email`, `customer_name`, см. заголовок `../tilda/inbound.ts`).
 * - Номер заявки — служебное поле `tranid` (Lead ID, задокументировано в
 *   help.tilda.cc/forms/webhook), а не `order_id` из «списка соответствия
 *   полей» платёжной интеграции.
 * - В служебном наборе полей формы суммы нет вовсе — вебхук формы вообще не
 *   привязан к оплате (это подтверждено документацией Tilda: там описаны
 *   только `tranid`/`formid`/`COOKIES`, про сумму или оплату ни слова).
 *   Поэтому продавец обязан завести в форме СВОЁ поле с именем переменной
 *   `Payment`, содержащее сумму заказа в тенге (см. `README.md`) — другого
 *   источника суммы у нас нет. Этот POST приходит на СЕРВЕР от
 *   инфраструктуры Tilda, а не через браузер покупателя (см. заголовок
 *   `../tilda/inbound.ts` — там ровно об этом различии для основного
 *   входа), но раз подписи нет вовсе, подделать тело запроса напрямую может
 *   и кто угодно, кто узнает адрес вебхука, — поэтому это по-прежнему
 *   запасной вход, а не замена основному.
 * - Tilda проверяет доступность вебхука запросом с полем `test=test` и
 *   ждёт ответ 200 в течение пяти секунд (задокументировано в
 *   help.tilda.cc/forms/webhook) — отвечаем немедленно, не трогая ни курс,
 *   ни базу данных.
 * - При любом ответе, кроме 200, Tilda повторяет запрос ещё дважды с
 *   интервалом в минуту — значит обработчик обязан быть идемпотентным по
 *   `tranid`. Эту идемпотентность даёт `createPaymentFor` (задача 5): при
 *   повторном `tildaOrderId` он возвращает уже существующий заказ, а не
 *   заводит второй (проверено `DuplicateOrderError` и ограничением `UNIQUE`
 *   в `../db.ts`).
 *
 * ЭТОТ ПУТЬ НЕ ПРОВЕРЕН НАСТОЯЩИМ ЗАКАЗОМ Tilda (см. `README.md`, раздел
 * «Ограничения запасного входа», и `извлечьСумму` ниже) — разбор суммы
 * терпимый именно поэтому: он пробует несколько вероятных вариантов и
 * честно отказывает с телом запроса в журнале, если ни один не подошёл,
 * вместо того чтобы притворяться, будто формат уже подтверждён вживую.
 */
import type { IncomingMessage, ServerResponse } from 'node:http';
import { createPaymentFor, OrderConflictError, type TildaOrder } from '../tilda/inbound.js';
import { прочитатьТело, разобратьUrlencoded, ТелоСлишкомБольшое } from './routes-pay.js';
import type { ЗависимостиСервера } from './server.js';

/**
 * Приставка номера заказа этого (неподписанного) входа — разводит его
 * пространство номеров с основным, подписанным входом (`tilda/inbound.ts`,
 * `order_id`) НАВСЕГДА, а не только пока оба совпадают по формату.
 *
 * Ревью на живом сервере, найдено НЕ рассуждением: `tranid` вебхука формы и
 * `order_id` платёжной интеграции — оба числа Tilda, оба видны посторонним
 * (номер проекта — в разметке страниц, номера заказов идут подряд), а
 * `createPaymentFor` при совпадении номера отдавал уже существующую запись
 * без сверки условий (это исправлено отдельно, `OrderConflictError`) — но
 * само пересечение номеров было ГЛАВНОЙ причиной, почему подмена вообще
 * была возможна: посторонний заранее портил номер будущего настоящего
 * заказа неподписанной заявкой на один тенге. С приставкой заявка формы
 * пишется как `form:482910`, платёжная интеграция — как раньше, `482910`:
 * столкновение двух входов на одном номере теперь структурно невозможно, а
 * не только отловлено проверкой условий постфактум.
 */
const ПРИСТАВКА_НОМЕРА = 'form:';

const ЗАГОЛОВКИ_ТЕКСТ = { 'content-type': 'text/plain; charset=utf-8' } as const;

/**
 * Формат суммы — тот же, что и у основного входа (см. `ФОРМАТ_СУММЫ` в
 * `../tilda/inbound.ts`). Продублирован намеренно, а не импортирован:
 * основной файл не экспортирует эту константу из своего публичного API, и
 * расширять его ради одного запасного входа — не в рамках этой задачи.
 */
const ФОРМАТ_СУММЫ = /^\d+(\.\d{1,2})?$/;
const МАКСИМАЛЬНАЯ_СУММА_KZT = 100_000_000;

/**
 * Отдельные поля верхнего уровня, в которых может обнаружиться сумма, если
 * `payment` не оказался JSON-объектом с `amount` внутри (см. `извлечьСумму`
 * ниже) — в порядке убывания вероятности:
 *
 * - `Payment` — своё соглашение для ОБЫЧНОЙ формы (не корзины), которое
 *   продавец заводит сам как отдельное поле (см. `README.md`);
 * - `payment` — тот же `payment`, но не JSON, а голое число (на случай,
 *   если непроверенные сведения о формате корзины не подтвердятся);
 * - `amount`, `Amount` — самые очевидные общеупотребимые имена.
 */
const ВЕРОЯТНЫЕ_ПОЛЯ_СУММЫ = ['Payment', 'payment', 'amount', 'Amount'] as const;

/**
 * `payment` как JSON-объект с числовым или строковым `amount` внутри — по
 * НЕПРОВЕРЕННЫМ сведениям (см. заголовок файла), так вебхук корзины Tilda
 * шлёт состав заказа. Возвращает `null` на любом отклонении от этой формы
 * (не JSON, не объект, нет `amount`, `amount` не в нашем формате суммы) —
 * решать тут нечего, дальше пробуют другие варианты (`извлечьСумму`).
 */
function извлечьСуммуИзJsonPayment(значение: string): string | null {
  let разобранное: unknown;
  try {
    разобранное = JSON.parse(значение);
  } catch {
    return null;
  }
  if (typeof разобранное !== 'object' || разобранное === null || Array.isArray(разобранное)) {
    return null;
  }
  const amount = (разобранное as Record<string, unknown>).amount;
  if (typeof amount === 'string') {
    return ФОРМАТ_СУММЫ.test(amount) ? amount : null;
  }
  if (typeof amount === 'number' && Number.isFinite(amount)) {
    const строкой = String(amount);
    return ФОРМАТ_СУММЫ.test(строкой) ? строкой : null;
  }
  return null;
}

/**
 * Извлекает сумму заказа из тела вебхука — терпимо, а не догматично: этот
 * вход НЕ ПРОВЕРЕН настоящим заказом Tilda (см. заголовок файла), и делать
 * вид, что формат уже известен наверняка, было бы хуже честного «не знаю».
 * Порядок попыток: сначала `payment` как JSON-объект корзины, затем —
 * несколько вероятных отдельных полей (`ВЕРОЯТНЫЕ_ПОЛЯ_СУММЫ`). Если ничего
 * не подошло — возвращает `null`, и вызывающий код не гадает дальше, а
 * записывает в журнал ВСЁ тело запроса и честно отказывает (см.
 * `обработатьTildaWebhook`) — так, при первой же настоящей заявке, будет
 * видно, как Tilda прислала сумму на самом деле, и разбор можно будет
 * поправить по факту, а не по предположению.
 */
function извлечьСумму(поля: Record<string, string>): string | null {
  if (поля.payment) {
    const изJson = извлечьСуммуИзJsonPayment(поля.payment);
    if (изJson !== null) return изJson;
  }

  for (const имя of ВЕРОЯТНЫЕ_ПОЛЯ_СУММЫ) {
    const значение = поля[имя];
    if (значение !== undefined && ФОРМАТ_СУММЫ.test(значение)) return значение;
  }

  return null;
}

/** Потолок длины текстовых полей формы — та же защита, что и у `description`/`products` основного входа: тело правится в чужой (для нас) системе, доверять размеру нельзя. */
const МАКСИМАЛЬНАЯ_ДЛИНА_ПОЛЯ = 255;

function полеИлиNull(значение: string | undefined): string | null {
  if (!значение) return null;
  return значение.length > МАКСИМАЛЬНАЯ_ДЛИНА_ПОЛЯ ? значение.slice(0, МАКСИМАЛЬНАЯ_ДЛИНА_ПОЛЯ) : значение;
}

/**
 * Строка для админского списка заказов из имени и телефона покупателя —
 * единственных содержательных данных о нём, которые вообще приходят по
 * этому входу (Tilda хранит саму заявку у себя в разделе «Лиды» под тем же
 * `tranid` — продавец при необходимости сверяется там). `Order` не хранит
 * отдельных колонок под имя и телефон (см. `NewOrder` в `../db.ts` — их нет
 * и у основного входа), поэтому они попадают в `description`, единственное
 * поле заказа, которое показывается в списке заказов как есть.
 */
function описаниеИзФормы(поля: Record<string, string>): string | null {
  const части: string[] = [];
  if (поля.Name) части.push(`Имя: ${поля.Name}`);
  if (поля.Phone) части.push(`Телефон: ${поля.Phone}`);
  if (части.length === 0) return null;
  return полеИлиNull(части.join('; '));
}

export async function обработатьTildaWebhook(
  req: IncomingMessage,
  res: ServerResponse,
  deps: ЗависимостиСервера,
): Promise<void> {
  let тело: string;
  try {
    тело = await прочитатьТело(req);
  } catch (е) {
    if (е instanceof ТелоСлишкомБольшое) {
      res.writeHead(413, ЗАГОЛОВКИ_ТЕКСТ);
      // Сокет закрывается только из колбэка res.end(), после того как ответ
      // реально ушёл — тот же приём, что и в routes-pay.ts (найдено ревью
      // в настоящем браузере: req.destroy() раньше срока рвёт соединение).
      res.end('Тело запроса слишком велико', () => req.destroy());
      return;
    }
    throw е;
  }

  const поля = разобратьUrlencoded(тело);

  // Проверка доступности — Tilda ждёт 200 за пять секунд и не должна
  // получить задержку на курс или запись в базу (см. заголовок файла).
  // Проверяется ПЕРВОЙ, до какой-либо ещё обработки тела.
  if (поля.test === 'test') {
    res.writeHead(200, ЗАГОЛОВКИ_ТЕКСТ);
    res.end('OK');
    return;
  }

  const tranid = (поля.tranid ?? '').trim();
  if (!tranid) {
    deps.log.warn('Вебхук Tilda без поля tranid — заявку невозможно опознать', {});
    res.writeHead(400, ЗАГОЛОВКИ_ТЕКСТ);
    res.end('Не хватает поля tranid');
    return;
  }

  const суммаСтрокой = извлечьСумму(поля);
  if (суммаСтрокой === null) {
    // Не гадаем дальше (см. заголовок файла и `извлечьСумму`) — записываем
    // ВСЁ тело запроса: подписи и секретов в нём нет (вход и так без
    // подписи), а это единственный способ один раз увидеть, как Tilda
    // прислала сумму на самом деле, и поправить разбор по факту.
    deps.log.warn(
      'Вебхук Tilda: не удалось определить сумму заказа — ни payment (JSON), ни известные поля не подошли. ' +
        'Путь не проверен настоящим заказом (см. README) — тело запроса ниже поможет понять формат.',
      { tranid, телоЗапроса: поля },
    );
    res.writeHead(400, ЗАГОЛОВКИ_ТЕКСТ);
    res.end('Не удалось определить сумму заказа в вебхуке — подробности в журнале сервера');
    return;
  }

  const сумма = Number(суммаСтрокой);
  if (сумма <= 0 || сумма > МАКСИМАЛЬНАЯ_СУММА_KZT) {
    deps.log.warn('Вебхук Tilda: сумма вне допустимого диапазона', { tranid });
    res.writeHead(400, ЗАГОЛОВКИ_ТЕКСТ);
    res.end('Сумма заказа вне допустимого диапазона');
    return;
  }

  // Синтетический TildaOrder — как из основного входа (`../tilda/inbound.ts`),
  // но без подписи (см. заголовок файла: у формы Tilda её не бывает) и без
  // test_mode (в форме Tilda этого понятия нет вовсе).
  const заказ: TildaOrder = {
    orderId: ПРИСТАВКА_НОМЕРА + tranid,
    amountKzt: суммаСтрокой,
    currency: 'KZT',
    timestamp: String(Math.floor(Date.now() / 1000)),
    testMode: false,
    description: описаниеИзФормы(поля),
    products: null,
    email: полеИлиNull(поля.Email),
    phone: полеИлиNull(поля.Phone),
    customerName: полеИлиNull(поля.Name),
    notifyUrl: null,
    successUrl: null,
    failureUrl: null,
    // Пусто — не «подделанная подпись», а буквально её отсутствие (см.
    // заголовок файла). createPaymentFor кладёт это значение как есть в
    // tildaSignature — по пустой строке в списке заказов (задача 8) можно
    // отличить заказ этого входа от заказа с настоящей подписью Tilda.
    signature: '',
  };

  let сохранённый;
  try {
    сохранённый = await createPaymentFor(заказ, {
      store: deps.store,
      client: deps.client,
      config: deps.config,
      log: deps.log,
    });
  } catch (е) {
    if (е instanceof OrderConflictError) {
      // Уже залогировано внутри createPaymentFor с подробностями расхождения.
      // С приставкой `form:` (см. ПРИСТАВКА_НОМЕРА выше) эта ветка не должна
      // случаться от столкновения с платёжной интеграцией — но остаётся
      // возможной от повторной заявки формы с ДРУГИМ Payment под тем же
      // tranid, и тогда это тоже не 200: Tilda не должна решить, что заявка
      // принята как раньше.
      res.writeHead(409, ЗАГОЛОВКИ_ТЕКСТ);
      res.end('Заявка с этим номером уже принята с другими условиями');
      return;
    }
    // Сбой курса, сети или RPC — не вина того, кто заполнил форму: продать
    // по неизвестному курсу хуже отказа (см. `createPaymentFor`). Tilda при
    // ответе, отличном от 200, повторит запрос — идемпотентность создания
    // заказа (см. заголовок файла) делает повтор безопасным.
    deps.log.error('Не удалось подготовить платёж по вебхуку Tilda', {
      tranid,
      сообщение: (е as Error).message,
    });
    res.writeHead(502, ЗАГОЛОВКИ_ТЕКСТ);
    res.end('Оплата временно недоступна, попробуйте ещё раз позже');
    return;
  }

  // Ни ключа страницы оплаты (`сохранённый.token`), ни любого другого
  // секрета — в журнал (см. заголовок `../mailer.ts` про то же самое
  // ограничение на `order.token`). Номера заявки достаточно для наблюдения.
  deps.log.info('Заявка по вебхуку Tilda принята: заказ создан или уже существовал', { tranid });

  res.writeHead(200, ЗАГОЛОВКИ_ТЕКСТ);
  res.end('OK');
}
