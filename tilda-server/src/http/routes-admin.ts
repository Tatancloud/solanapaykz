/* ------------------------- пароль, попытки ------------------------- */

function паролиСовпадают(введённый: string, ожидаемый: string): boolean {
  const а = Buffer.from(введённый, 'utf8');
  const б = Buffer.from(ожидаемый, 'utf8');
  // timingSafeEqual бросает на буферах разной длины — сравнение длины не
  // сравнением содержимого постоянным временем не является, но короче
  // ожидаемого пароль всё равно был бы отвергнут после полного сравнения;
  // ранний выход здесь экономит лишь на заведомо неверном пароле другой
  // длины, а не выдаёт ничего о содержимом (как и в `signature.ts`).
  if (а.length !== б.length) return false;
  return timingSafeEqual(а, б);
}

const ОКНО_ПОПЫТОК_MS = 15 * 60 * 1000;
const МАКСИМУМ_ПОПЫТОК = 5;

/**
 * Потолок числа РАЗНЫХ адресов одновременно в карте попыток входа.
 *
 * Правка финального ревью: карта росла без предела — истёкшие записи
 * никогда не удалялись, только читались как «неактуальные» (см.
 * `записьВОкне`) и оставались лежать в памяти вечно. Замер ревью — плюс
 * ~140 МБ на миллион поддельных адресов (`X-Forwarded-For` подделывается
 * с доверенного сокета так же легко, как и что угодно ещё в заголовках
 * запроса). Опрятная чистка устаревших записей (см. `отметитьНеудачу`)
 * закрывает обычный случай — карта не растёт, пока адреса, переставшие
 * атаковать, выходят из своего пятнадцатиминутного окна. Этот потолок —
 * вторая, самостоятельная линия обороны на случай потока из ОГРОМНОГО
 * числа РАЗНЫХ адресов ВНУТРИ одного окна, когда чистка устаревших ничего
 * не удаляет просто потому, что удалять пока нечего.
 */
export const МАКСИМАЛЬНЫЙ_РАЗМЕР_КАРТЫ_ПОПЫТОК = 5000;

interface ЗаписьПопыток {
  count: number;
  windowStart: number;
}

/**
 * Счётчик попыток входа — вынесен в отдельную пуристую фабрику ради теста:
 * `createAdminRoutes` не отдаёт доступ к своей внутренней карте наружу
 * (и не должен, это боевой код), а тест правки ревью обязан видеть
 * количество записей в карте, а не только наблюдаемое через HTTP поведение
 * лимита — тем же приёмом, что и `клиентскийАдрес` выше: чистая функция
 * (здесь — фабрика), проверяемая без настоящего HTTP-соединения.
 */
export interface СчётчикПопытокВхода {
  лимитИсчерпан(ip: string, сейчасMs: number): boolean;
  отметитьНеудачу(ip: string, сейчасMs: number): void;
  сброситьПопытки(ip: string): void;
  /** Только для наблюдения и теста — число адресов, сейчас хранимых в карте. */
  размер(): number;
}

export function создатьСчётчикПопытокВхода(): СчётчикПопытокВхода {
  const попыткиВхода = new Map<string, ЗаписьПопыток>();

  /** Свежа ли запись счётчика для адреса — окно истекает, счётчик обнуляется, а не копится вечно. */
  function записьВОкне(ip: string, сейчасMs: number): ЗаписьПопыток | undefined {
    const запись = попыткиВхода.get(ip);
    if (!запись || сейчасMs - запись.windowStart > ОКНО_ПОПЫТОК_MS) return undefined;
    return запись;
  }

  function лимитИсчерпан(ip: string, сейчасMs: number): boolean {
    const запись = записьВОкне(ip, сейчасMs);
    return запись !== undefined && запись.count >= МАКСИМУМ_ПОПЫТОК;
  }

  function отметитьНеудачу(ip: string, сейчасMs: number): void {
    const запись = записьВОкне(ip, сейчасMs);
    if (запись) {
      запись.count += 1;
      return;
    }

    // Новый адрес в карте — повод почистить всё, что уже вышло из своего
    // окна: без этого карта растёт без предела, пока хоть кто-нибудь (не
    // обязательно один и тот же адрес) продолжает ошибаться паролем.
    for (const [чужойIp, чужаяЗапись] of попыткиВхода) {
      if (сейчасMs - чужаяЗапись.windowStart > ОКНО_ПОПЫТОК_MS) {
        попыткиВхода.delete(чужойIp);
      }
    }

    // И жёсткий потолок сверх чистки устаревших: поток из ОГРОМНОГО числа
    // РАЗНЫХ, ещё не истёкших (в пределах одного окна) адресов чистка не
    // уменьшит ни на запись. Новые адреса сверх потолка просто не
    // запоминаются — лимит входа для них при этом не считается исчерпанным
    // (см. `лимитИсчерпан`: нет записи — не исчерпан), это осознанный
    // компромисс: разумный потолок недостижим для настоящего разнообразия
    // посетителей одного продавца, а вот заливка миллионом поддельных
    // адресов не должна расти в памяти без предела.
    if (попыткиВхода.size < МАКСИМАЛЬНЫЙ_РАЗМЕР_КАРТЫ_ПОПЫТОК) {
      попыткиВхода.set(ip, { count: 1, windowStart: сейчасMs });
    }
  }

  function сброситьПопытки(ip: string): void {
    попыткиВхода.delete(ip);
  }

  return { лимитИсчерпан, отметитьНеудачу, сброситьПопытки, размер: () => попыткиВхода.size };
}

/**
 * Адреса, с которых доверяем заголовку `X-Forwarded-For`, по умолчанию —
 * когда `config.trustedProxyAddresses` не задан явно. Сам процесс слушает
 * только на loopback (см. `config.example.json`, `listenPort`), и обратный
 * прокси (nginx, задача 9) будет обращаться к нему тоже с loopback — это
 * годится, пока сервер и прокси на одном хосте вне контейнера, либо
 * контейнер поднят в сети хоста. Запрос, пришедший СРАЗУ с loopback-адреса
 * на сокете, — это прокси; запрос с любого другого адреса на сокете — это
 * либо прямое обращение в обход прокси, либо сам прокси на другом хосте —
 * заголовку в обоих случаях доверять нельзя.
 *
 * Список — настройка (`Config.trustedProxyAddresses`), а не жёстко зашитая
 * константа: правка ревью задачи 9. Первая версия развёртывания решала ту
 * же задачу иначе — переводила весь контейнер в сеть хоста
 * (`network_mode: host`), чтобы сокет действительно видел loopback. Это
 * лечило симптом дорогой ценой (контейнер занимает порт на весь хост, а не
 * только для себя) вместо настоящей причины — того, что доверенный адрес
 * был жёстко привязан к loopback. Теперь контейнер может работать в обычной
 * сети Docker (мост, порт публикуется только на `127.0.0.1` — см.
 * `docker-compose.yml`), а в `config.json` достаточно добавить адрес шлюза
 * этого моста в `trustedProxyAddresses`.
 */
export const АДРЕСА_ДОВЕРЕННЫХ_ПРОКСИ_ПО_УМОЛЧАНИЮ: readonly string[] = ['127.0.0.1', '::1', '::ffff:127.0.0.1'];

/**
 * Адрес клиента для ограничения попыток входа — не всегда адрес TCP-сокета.
 *
 * Правка ревью: за обратным прокси на этом же хосте (nginx, задача 9) сокет
 * видит один и тот же адрес (сам прокси) для всех посетителей — без этого
 * различения счётчик попыток схлопнулся бы в один общий на всех сразу, и
 * любой прохожий пятью неверными паролями закрывал бы вход настоящему
 * продавцу на пятнадцать минут. Поэтому заголовку `X-Forwarded-For`
 * доверяем ТОЛЬКО когда сам сокет — доверенный прокси (`доверенныеАдреса`,
 * по умолчанию `АДРЕСА_ДОВЕРЕННЫХ_ПРОКСИ_ПО_УМОЛЧАНИЮ`, а в бою —
 * `config.trustedProxyAddresses`): иначе любой внешний клиент, обратившись
 * напрямую в обход прокси, мог бы подставить в этом заголовке чужой адрес
 * и обнулить чужой счётчик или скрыть свой собственный подбор пароля.
 *
 * Экспортирована пуристой функцией от трёх значений, а не от
 * `IncomingMessage` целиком, — так её проверяют юнит-тестом без настоящего
 * HTTP-соединения (см. `tests/admin.test.ts`), тем же приёмом, что и
 * `decide()` в `decision.ts`. Третий параметр необязателен и по умолчанию
 * равен старому жёстко зашитому списку — старые вызовы и тесты без него
 * продолжают работать как раньше.
 */
export function клиентскийАдрес(
  адресСокета: string | undefined,
  заголовокForwardedFor: string | string[] | undefined,
  доверенныеАдреса: readonly string[] = АДРЕСА_ДОВЕРЕННЫХ_ПРОКСИ_ПО_УМОЛЧАНИЮ,
): string {
  const сокет = адресСокета ?? 'неизвестный-адрес';
  if (!доверенныеАдреса.includes(сокет)) return сокет;

  // Node склеивает повторные заголовки через запятую сам, но на случай
  // массива (некоторые обёртки прокидывают его так) берём первое значение.
  const значение = Array.isArray(заголовокForwardedFor) ? заголовокForwardedFor[0] : заголовокForwardedFor;
  if (!значение) return сокет;

  // Самый ПРАВЫЙ адрес в списке — тот, что дописал наш собственный,
  // доверенный прокси, а не тот, что прислал клиент.
  //
  // Правка финального ревью — здесь была настоящая дыра, а не только
  // теоретическая: nginx (`nginx.example.conf`) настроен на
  // `proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for`, а эта
  // переменная СОХРАНЯЕТ заголовок, пришедший от клиента, и ДОПИСЫВАЕТ
  // настоящий адрес СПРАВА — самый левый элемент как раз и есть то, что
  // подставил сам клиент. Прежний код брал именно левый элемент, доверяя
  // комментарию «самый левый — исходный клиент», который для дописывающего
  // прокси неверен: ревью проверило запросом с семью разными поддельными
  // заголовками — лимит не срабатывал ни разу. Правый элемент, наоборот,
  // подделать нельзя: его подставляет nginx из TCP-соединения, а не из
  // заголовка запроса, и клиент до него дотянуться не может.
  const части = значение.split(',').map((часть) => часть.trim()).filter((часть) => часть.length > 0);
  const последний = части[части.length - 1];
  return последний ?? сокет;
}

function ipЗапроса(req: IncomingMessage, config: ЗависимостиСервера['config']): string {
  return клиентскийАдрес(req.socket.remoteAddress, req.headers['x-forwarded-for'], config.trustedProxyAddresses);
}

