const ЗАГОЛОВКИ_HTML = { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'no-store' } as const;
const ЗАГОЛОВКИ_ТЕКСТ = { 'content-type': 'text/plain; charset=utf-8', 'cache-control': 'no-store' } as const;
/** Заголовки редиректов (303) этого файла — без тела, но с тем же запретом кеширования. */
const ЗАГОЛОВКИ_РЕДИРЕКТА = { 'cache-control': 'no-store' } as const;

const ИМЯ_КУКИ = 'admin_session';
const СРОК_СЕССИИ_СЕК = 12 * 60 * 60;

/* ---------------------------- сессия ---------------------------- */

/**
 * Ключ HMAC для подписи сессии — не сам `adminPassword`, а его HMAC с
 * постоянной меткой `'сессия'`. Так у `adminPassword` остаётся одно
 * назначение (сравниваться с введённым паролем), а не два, и смена пароля
 * автоматически обесценивает все выданные раньше токены — оба свойства
 * важны сами по себе, не только для устранения риска (см. заголовок файла).
 */
function ключСессии(adminPassword: string): Buffer {
  return createHmac('sha256', adminPassword).update('сессия').digest();
}

/** Подписанный токен сессии: `<истекает-unix-сек>.<поколение>.<hex-hmac>`. Оба числовых поля — только цифры, разделитель однозначен. */
function токенСессии(ключ: Buffer, истекает: number, поколение: number): string {
  const подпись = createHmac('sha256', ключ).update(`${истекает}.${поколение}`).digest('hex');
  return `${истекает}.${поколение}.${подпись}`;
}

function сессияДействительна(
  значение: string | undefined,
  ключ: Buffer,
  текущееПоколение: number,
  сейчасСек: number,
): boolean {
  if (!значение) return false;
  const части = значение.split('.');
  if (части.length !== 3) return false;
  const [истекаетСтрока, поколениеСтрока, подпись] = части as [string, string, string];
  if (!/^\d+$/.test(истекаетСтрока) || !/^\d+$/.test(поколениеСтрока)) return false;

  const ожидаемая = createHmac('sha256', ключ).update(`${истекаетСтрока}.${поколениеСтрока}`).digest('hex');
  const а = Buffer.from(подпись, 'utf8');
  const б = Buffer.from(ожидаемая, 'utf8');
  if (а.length !== б.length || !timingSafeEqual(а, б)) return false;

  // Поколение сверяется ТОЛЬКО после того, как подпись подтвердила, что
  // числа в токене не подделаны — иначе можно было бы прочитать чужое
  // текущее поколение простым перебором значений в куке, не зная секрета.
  if (Number(поколениеСтрока) !== текущееПоколение) return false;

  return Number(истекаетСтрока) > сейчасСек;
}

function прочитатьКуку(req: IncomingMessage, имя: string): string | undefined {
  const заголовок = req.headers.cookie;
  if (!заголовок) return undefined;
  for (const часть of заголовок.split(';')) {
    const равно = часть.indexOf('=');
    if (равно < 0) continue;
    if (часть.slice(0, равно).trim() === имя) return часть.slice(равно + 1).trim();
  }
  return undefined;
}

function естьСессия(req: IncomingMessage, deps: ЗависимостиСервера): boolean {
  const значение = прочитатьКуку(req, ИМЯ_КУКИ);
  return сессияДействительна(
    значение,
    ключСессии(deps.config.adminPassword),
    deps.store.sessionGeneration(),
    Math.floor(Date.now() / 1000),
  );
}

/** `Secure` — кука уходит только по HTTPS; `HttpOnly` — недоступна из JS на странице; `SameSite=Strict` — не уходит с чужого сайта. Всё три — по заданию. */
function кукаВхода(значение: string): string {
  return `${ИМЯ_КУКИ}=${значение}; Path=/; Max-Age=${СРОК_СЕССИИ_СЕК}; HttpOnly; Secure; SameSite=Strict`;
}

const КУКА_ВЫХОДА = `${ИМЯ_КУКИ}=; Path=/; Max-Age=0; HttpOnly; Secure; SameSite=Strict`;

/* ------------------------- пароль, попытки ------------------------- */

function паролиСовпадают(введённый: string, ожидаемый: string): boolean {
  const а = Buffer.from(введённый, 'utf8');
  const б = Buffer.from(ожидаемый, 'utf8');
  // timingSafeEqual бросает на буферах разной длины — сравнение длины не
  // сравнением содержимого постоянным временем не является, но короче
  // ожидаемого пароль всё равно был бы отвергнут после полного сравнения;
  // ранний выход здесь экономит лишь на заведомо неверном пароле другой
  // длины, а не выдаёт ничего о содержимом (как и в `signature.ts`).
  if (а.length !== б.length) return false;
  return timingSafeEqual(а, б);
}

const ОКНО_ПОПЫТОК_MS = 15 * 60 * 1000;
const МАКСИМУМ_ПОПЫТОК = 5;

interface ЗаписьПопыток {
  count: number;
  windowStart: number;
}

/**
 * Адреса, с которых доверяем заголовку `X-Forwarded-For` — сам процесс
 * слушает только на loopback (см. `config.example.json`, `listenPort`), и
 * обратный прокси (nginx, задача 9) будет обращаться к нему тоже с
 * loopback. Запрос, пришедший СРАЗУ с loopback-адреса на сокете, — это
 * прокси; запрос с любого другого адреса на сокете — это либо прямое
 * обращение в обход прокси, либо сам прокси на другом хосте (сегодня не
 * наш случай) — заголовку в обоих случаях доверять нельзя.
 */
const АДРЕСА_ДОВЕРЕННЫХ_ПРОКСИ: ReadonlySet<string> = new Set(['127.0.0.1', '::1', '::ffff:127.0.0.1']);

/**
 * Адрес клиента для ограничения попыток входа — не всегда адрес TCP-сокета.
 *
 * Правка ревью: за обратным прокси на этом же хосте (nginx, задача 9) сокет
 * видит один и тот же адрес (сам прокси) для всех посетителей — без этого
 * различения счётчик попыток схлопнулся бы в один общий на всех сразу, и
 * любой прохожий пятью неверными паролями закрывал бы вход настоящему
 * продавцу на пятнадцать минут. Поэтому заголовку `X-Forwarded-For`
 * доверяем ТОЛЬКО когда сам сокет — доверенный прокси (см.
 * `АДРЕСА_ДОВЕРЕННЫХ_ПРОКСИ`): иначе любой внешний клиент, обратившись
 * напрямую в обход прокси, мог бы подставить в этом заголовке чужой адрес
 * и обнулить чужой счётчик или скрыть свой собственный подбор пароля.
 *
 * Экспортирована пуристой функцией от двух строк, а не от `IncomingMessage`
 * целиком, — так её проверяют юнит-тестом без настоящего HTTP-соединения
 * (см. `tests/admin.test.ts`), тем же приёмом, что и `decide()` в
 * `decision.ts`.
 */
export function клиентскийАдрес(
  адресСокета: string | undefined,
  заголовокForwardedFor: string | string[] | undefined,
): string {
  const сокет = адресСокета ?? 'неизвестный-адрес';
  if (!АДРЕСА_ДОВЕРЕННЫХ_ПРОКСИ.has(сокет)) return сокет;

  // Node склеивает повторные заголовки через запятую сам, но на случай
  // массива (некоторые обёртки прокидывают его так) берём первое значение.
  const значение = Array.isArray(заголовокForwardedFor) ? заголовокForwardedFor[0] : заголовокForwardedFor;
  if (!значение) return сокет;

  // Самый левый адрес в списке — исходный клиент; последующие (если есть)
  // добавлены промежуточными прокси при цепочке из нескольких. При одном
  // прокси перед нами (типичная схема задачи 9) в заголовке будет ровно
  // один адрес.
  const первый = значение.split(',')[0]?.trim();
  return первый && первый.length > 0 ? первый : сокет;
}

function ipЗапроса(req: IncomingMessage): string {
  return клиентскийАдрес(req.socket.remoteAddress, req.headers['x-forwarded-for']);
}

