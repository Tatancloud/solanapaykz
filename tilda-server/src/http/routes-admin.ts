/**
 * `GET /admin` — список заказов под паролем; `GET /admin/login` — форма
 * входа; `POST /admin/login` — проверка пароля и выдача сессии;
 * `POST /admin/logout` — выход.
 *
 * Список — не украшение поверх писем продавцу (`../mailer.ts`): Tilda не
 * даёт пометить заказ оплаченным иначе как нашим уведомлением, и часть
 * заказов неизбежно застрянет — платёж есть, а Tilda о нём не знает, сумма
 * не сошлась, платёж пришёл после истечения цены. Это разбирает человек, и
 * ему нужна картина целиком, а не лента писем. Отметка «Tilda подтвердила»/
 * «Tilda не подтвердила» обязательна: без неё нечем заметить, что заказ
 * оплачен, а магазин об этом не знает.
 *
 * Безопасность входа:
 * - пароль сравнивается постоянным временем (`timingSafeEqual`);
 * - попытки входа ограничены — пять за пятнадцать минут на адрес,
 *   независимо от того, верным или неверным был очередной пароль;
 * - сессия — подписанная кука на 12 часов. Ключ подписи — не сам
 *   `adminPassword`, а отдельное значение, выведенное из него HMAC'ом с
 *   постоянной меткой (`ключСессии`, ниже): у `adminPassword` уже есть своё
 *   назначение — сравниваться с введённым паролем, — и не стоит давать
 *   одному секрету второе, даже когда прямой риск от этого не растёт.
 *   Полезный побочный эффект: смена пароля меняет и производный ключ, а
 *   значит обесценивает все выданные раньше сессии сама по себе;
 * - кука — `HttpOnly`, `Secure`, `SameSite=Strict`;
 * - токен несёт номер поколения сессий (`Store.sessionGeneration`, задача
 *   8, правка ревью). Выход (`POST /admin/logout`) увеличивает поколение в
 *   базе — все ранее выданные токены, включая тот, что мог утечь и остаться
 *   в чужом браузере, сразу перестают приниматься, а не только тот, что
 *   кука на этом устройстве попросят забыть.
 *
 * Всё, что в разметку списка попадает из заказа (номер, суммы, состояние,
 * подпись транзакции), экранируется через `экранироватьHtml` — те же
 * значения, что видит покупатель на странице оплаты, и по той же причине
 * (см. заголовок `html.ts`): формально они «наши», но подпись транзакции,
 * например, приходит из ответа RPC-узла, а не изнутри проекта.
 *
 * `Cache-Control: no-store` на всех ответах этого файла (правка ревью,
 * найдено в настоящем браузере): без него вход → список → «Выйти» → кнопка
 * «Назад» браузера показывала список заново из кеша, без единого сетевого
 * запроса — сервер эту куку уже не принял бы, но на экране чужого или
 * общего компьютера данные заказов оставались видны. Заголовка одного
 * недостаточно: он не гарантированно исключает страницу из back/forward
 * cache браузера (bfcache) — тот же сценарий воспроизведён и С этим
 * заголовком, браузер всё равно восстановил список из кеша без единого
 * запроса к серверу. Вторая линия обороны — `public/admin.js`
 * (`pageshow`/`event.persisted`): страница, показанная ИЗ bfcache,
 * безусловно перезагружается, и тогда сервер уже видит актуальную куку.
 *
 * Ограничение попыток входа считает по адресу клиента, а не всегда по
 * адресу TCP-сокета — см. `клиентскийАдрес` ниже: за обратным прокси
 * (nginx, задача 9) сокет для всех посетителей один и тот же, и без этого
 * различения счётчик схлопнулся бы в общий на всех сразу.
 */
