/**
 * `GET /pay/:token` — страница оплаты, которую видит покупатель, и
 * `GET /api/status/:token` — состояние заказа для опроса из `checkout.js`.
 *
 * Оба маршрута принимают на вход только `token`: случайный ключ страницы
 * оплаты (задача 5, `randomBytes(16).toString('hex')`), а не номер заказа —
 * подобрать чужой перебором номеров здесь нельзя в принципе.
 */
import type { ServerResponse } from 'node:http';
import { timingSafeEqual } from 'node:crypto';
import { toString as qrCodeToString } from 'qrcode';
import { checkOrder } from '../checker.js';
import type { Order } from '../db.js';
import { страница404, страницаИтога, страницаОплаты, страницаСообщения, текстСостояния } from './html.js';
import type { ЗависимостиСервера } from './server.js';

const ЗАГОЛОВКИ_HTML = { 'content-type': 'text/html; charset=utf-8' } as const;
const ЗАГОЛОВКИ_JSON = { 'content-type': 'application/json; charset=utf-8' } as const;

/**
 * Ищет заказ по ключу страницы. Помимо точного совпадения, которое уже
 * гарантирует `WHERE token = ?` в `Store` (задача 3), сверяет найденный
 * токен со входным через `timingSafeEqual` — по заданию. Само по себе
 * равенство здесь уже установлено запросом к базе, так что эта проверка не
 * отсекает ничего нового; но она не даёт будущей замене реализации `Store`
 * (например, поиском без учёта регистра или по префиксу) тихо превратить
 * точное совпадение в примерное.
 *
 * Ответ на несуществующий и на чужой (но существующий) ключ обязан быть
 * одинаковым — оба идут через один и тот же `null`.
 */
function найтиЗаказПоТокену(token: string, store: ЗависимостиСервера['store']): Order | null {
  const заказ = store.findByToken(token);
  if (!заказ) return null;

  const а = Buffer.from(token, 'utf8');
  const б = Buffer.from(заказ.token, 'utf8');
  if (а.length !== б.length || !timingSafeEqual(а, б)) return null;

  return заказ;
}

/** Секунд до истечения цены — на момент этого запроса, не на момент создания заказа. */
function секундОсталосьСейчас(order: Order): number {
  return Math.max(0, order.expiresAt - Math.floor(Date.now() / 1000));
}

/**
 * Сколько максимум ждать `checkOrder` на одном опросе, прежде чем ответить
 * по текущей записи в базе, не дожидаясь его возврата.
 *
 * Уведомление Tilda (случай «оплачен») `checkOrder` не ожидает — оно
 * запускается фоном (см. `checker.ts`). Но сама проверка платежа
 * (`checkPayment`) по-прежнему ожидается напрямую, а её тайм-аут (30
 * секунд, тоже настраиваемый) больше типичного интервала опроса — этот
 * тайм-аут страхует именно от такого зависания, а не от долгого
 * уведомления. `checkOrder` при этом не прерывается и не отменяется —
 * тайм-аут только прекращает ЖДАТЬ его здесь; ответ строится по текущей
 * записи в базе, а не по возврату `checkOrder`.
 */
const ТАЙМАУТ_ОПРОСА_ПРОВЕРКИ_MS_ПО_УМОЛЧАНИЮ = 8_000;

function истечёт(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Кеш ответа `GET /api/status/:token` по ключу страницы, на несколько
 * секунд — правка финального ревью, тот же приём, что и в плагине
 * WooCommerce того же проекта (`Ajax.php`, `POLL_CACHE_TTL_SECONDS`).
 *
 * Опрос из вкладки покупателя (`public/checkout.js`) идёт раз в 5 секунд и
 * без ограничений вызывал полную проверку платежа НА КАЖДЫЙ запрос: ни
 * кеша, ни минимального интервала. Несколько секунд кеша убирают повторный
 * `checkOrder` (а с ним — поход в платный RPC-узел и попытку уведомления
 * Tilda) на дубли одного и того же опроса — двойную вкладку, автоматический
 * повтор браузера, реальный обгон следующего интервала опроса медленной
 * сетью, — не меняя ощутимо задержку для покупателя: кеш короче интервала
 * опроса, так что ответ обновляется на каждом опросе снаружи короткого
 * всплеска дублей.
 *
 * Карта в памяти процесса (сервер — один процесс, тот же приём, что у
 * `занятыеЗаказы` в `../checker.ts`) — переживать перезапуск ей не нужно,
 * а вот расти без предела не должна: при добавлении новой записи попутно
 * выметаются все, что уже истекли (тот же приём, что и в
 * `создатьСчётчикПопытокВхода`, `../http/routes-admin.ts`).
 */
const ВРЕМЯ_КЕША_ОПРОСА_MS_ПО_УМОЛЧАНИЮ = 3_000;
const МАКСИМАЛЬНЫЙ_РАЗМЕР_КЕША_ОПРОСА = 5_000;

interface ЗаписьКешаОпроса {
  истекаетMs: number;
  тело: string;
}

const кешОпроса = new Map<string, ЗаписьКешаОпроса>();

function положитьВКешОпроса(token: string, тело: string, времяКешаMs: number, сейчасMs: number): void {
  // Новая запись — повод почистить всё, что уже истекло, тем же приёмом,
  // что и у карты попыток входа (см. заголовок константы выше).
  for (const [чужойТокен, чужаяЗапись] of кешОпроса) {
    if (чужаяЗапись.истекаетMs <= сейчасMs) {
      кешОпроса.delete(чужойТокен);
    }
  }
  if (кешОпроса.size < МАКСИМАЛЬНЫЙ_РАЗМЕР_КЕША_ОПРОСА) {
    кешОпроса.set(token, { истекаетMs: сейчасMs + времяКешаMs, тело });
  }
}

export async function обработатьСтраницуОплаты(
  token: string,
  res: ServerResponse,
  deps: ЗависимостиСервера,
): Promise<void> {
  const заказ = найтиЗаказПоТокену(token, deps.store);
  if (!заказ) {
    res.writeHead(404, ЗАГОЛОВКИ_HTML);
    res.end(страница404());
    return;
  }

  // Заказу, который больше не ждёт оплаты (оплачен, отменён, разбирается
  // вручную), QR не показываем — это приглашение заплатить второй раз.
  if (заказ.state !== 'ожидает') {
    // Правка финального ревью (задача 4): покупатель, оплативший или не
    // успевший оплатить, возвращается на страницу магазина в Tilda, если
    // продавец её настроил (`config.successUrl`/`config.failureUrl`) —
    // иначе он навсегда остаётся на нашей странице итога: не видит
    // страницу «спасибо» магазина, не срабатывает очистка корзины и
    // аналитика Tilda. Адрес берём из настроек продавца, а не из
    // неподписанных полей запроса Tilda (`success_url`/`failure_url`,
    // см. заголовок `tilda/inbound.ts`) — иначе покупатель мог бы
    // подставить в них любой чужой адрес и получить открытую
    // переадресацию.
    //
    // Только два состояния редиректят: «оплачен»/«уведомлён» — на
    // успех, «просрочен» — на отказ (покупатель точно не заплатил).
    // «Не сошлось», «поздний» и «ошибка настроек» — не то же самое, что
    // однозначный успех или отказ: деньги могут быть уже у продавца
    // («поздний») или ситуация ждёт разбора человеком, и увести оттуда
    // покупателя молча значило бы скрыть от него, что происходит.
    const редиректНа =
      заказ.state === 'оплачен' || заказ.state === 'уведомлён'
        ? deps.config.successUrl
        : заказ.state === 'просрочен'
          ? deps.config.failureUrl
          : undefined;

    if (редиректНа) {
      res.writeHead(302, { location: редиректНа });
      res.end();
      return;
    }

    res.writeHead(200, ЗАГОЛОВКИ_HTML);
    res.end(страницаИтога(заказ));
    return;
  }

  let qrSvg: string;
  try {
    // QR строится из уже замороженной платёжной ссылки (`paymentUrl`),
    // сохранённой при создании заказа (задача 5) — не заново через SDK:
    // повторный вызов SDK выпустил бы новую случайную метку платежа
    // (`reference`), и деньги, отправленные по старому QR, перестали бы
    // находиться при проверке.
    qrSvg = await qrCodeToString(заказ.paymentUrl, { type: 'svg', margin: 1, width: 320 });
  } catch (е) {
    deps.log.error('Не удалось построить QR-код для страницы оплаты', {
      tildaOrderId: заказ.tildaOrderId,
      сообщение: (е as Error).message,
    });
    res.writeHead(200, ЗАГОЛОВКИ_HTML);
    res.end(
      страницаСообщения(
        заказ,
        'Оплата временно недоступна: не удалось построить QR-код. Свяжитесь с магазином.',
      ),
    );
    return;
  }

  res.writeHead(200, ЗАГОЛОВКИ_HTML);
  res.end(страницаОплаты(заказ, секундОсталосьСейчас(заказ), qrSvg));
}

export async function обработатьСтатус(
  token: string,
  res: ServerResponse,
  deps: ЗависимостиСервера,
): Promise<void> {
  const заказ = найтиЗаказПоТокену(token, deps.store);
  if (!заказ) {
    res.writeHead(404, ЗАГОЛОВКИ_JSON);
    res.end(JSON.stringify({ error: 'Заказ не найден' }));
    return;
  }

  const времяКешаMs = deps.тест?.кешОпросаMs ?? ВРЕМЯ_КЕША_ОПРОСА_MS_ПО_УМОЛЧАНИЮ;
  const сейчасMs = Date.now();
  const закешированный = кешОпроса.get(token);
  if (закешированный && закешированный.истекаетMs > сейчасMs) {
    res.writeHead(200, ЗАГОЛОВКИ_JSON);
    res.end(закешированный.тело);
    return;
  }

  // Опрос — второй (наравне с фоновым обходом) независимый триггер
  // проверки платежа: покупатель может увидеть подтверждение раньше, чем
  // до заказа дойдёт очередь обхода раз в минуту.
  await Promise.race([
    checkOrder(заказ, deps).catch((е: unknown) => {
      deps.log.error('checkOrder упал при опросе статуса — отвечаем по текущей записи в базе', {
        tildaOrderId: заказ.tildaOrderId,
        сообщение: (е as Error).message,
      });
    }),
    истечёт(deps.тест?.таймаутОпросаMs ?? ТАЙМАУТ_ОПРОСА_ПРОВЕРКИ_MS_ПО_УМОЛЧАНИЮ),
  ]);
  const свежий = найтиЗаказПоТокену(token, deps.store) ?? заказ;

  // Ни суммы, ни адреса получателя, ни метки платежа: страница уже
  // показала их тому, кто знает ключ, а ответ опроса — лишний канал
  // утечки (см. задание).
  const тело = JSON.stringify({
    state: свежий.state,
    message: текстСостояния(свежий.state),
    secondsLeft: свежий.state === 'ожидает' ? секундОсталосьСейчас(свежий) : 0,
  });

  положитьВКешОпроса(token, тело, времяКешаMs, сейчасMs);

  res.writeHead(200, ЗАГОЛОВКИ_JSON);
  res.end(тело);
}
