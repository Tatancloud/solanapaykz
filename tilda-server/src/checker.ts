/**
 * Проверка платежа по одному заказу и фоновый обход незакрытых заказов.
 *
 * Опрос из браузера покупателя (`http/routes-page.ts`) и обход по таймеру
 * (`startChecker`) — два независимых пути к одному заказу, оба вызывают
 * `checkOrder` и оба могут увидеть один и тот же заказ одновременно —
 * будь то ещё не проверенный платёж или уже подтверждённый, но пока не
 * уведомлённый. Защита — две отдельные карты в памяти процесса (годится,
 * потому что сервер — один процесс): `занятыеЗаказы` на время проверки
 * блокчейна и записи решения, `уведомляемыеЗаказы` — отдельно, на время
 * самой отправки уведомления (она может идти фоном уже после того, как
 * `занятыеЗаказы` снят, см. `уведомитьИЗакрыть`). Заказ в закрытом
 * состоянии (`не сошлось`, `поздний`, `просрочен`, `уведомлён`) `decide()`
 * в белый список не пускает; заказ «оплачен» с ещё не доставленным
 * уведомлением `decide()` вообще не видит — его перехватывает
 * `довезтиУведомление` раньше. Аналог на PHP:
 * `demo-shop/plugin/includes/OrderChecker.php` + `OrderLock.php`.
 *
 * Письмо продавцу (`../mailer.ts`, задача 8) отправляется отсюда же — из
 * ЕДИНСТВЕННОГО места, где решение впервые применяется к заказу
 * (`применитьРешение`, три случая — «оплачен», «не сошлось», «поздний»).
 * Правка ревью: изначально `sendMerchantMail` была написана и покрыта
 * тестами, но её никто не вызывал из рабочего пути — продавец не получил
 * бы письмо никогда. «Просрочен» письма не шлёт: таких заказов (никто не
 * заплатил) будет много, и поток писем о них обесценил бы остальные.
 * Отправка не ожидается (как и `notifyTilda` — см. `уведомитьИЗакрыть`
 * ниже) — письмо не должно задерживать ни ответ на опрос покупателя, ни
 * обход остальных заказов. Второе письмо по тому же заказу не уйдёт: сам
 * `decide()` белым списком пускает `не сошлось`/`поздний`/`оплачен`
 * только для заказов, ещё бывших «ожидает»/«просрочен» — то есть решение,
 * а с ним и письмо, применяется к каждому заказу ровно один раз.
 */
import type { PaymentStatus, Quote } from '@solanapaykz/core';
import type { Config } from './config.js';
import { decide, type Decision } from './decision.js';
import type { Order, Store } from './db.js';
import type { Log } from './log.js';
import { sendMerchantMail, type ОтправкаПисьма } from './mailer.js';
import { notifyTilda, type NotifyTestHooks } from './tilda/notify.js';

/** Минимально нужный от SDK метод — не весь `SolanaPayKZ`, чтобы в тестах подменять без сети и RPC. */
export interface PaymentCheckerClient {
  checkPayment(params: { reference: string; quote: Quote }): Promise<PaymentStatus>;
}

/** Тестовые крюки этого модуля — не для боевого кода (см. `NotifyTestHooks`). */
