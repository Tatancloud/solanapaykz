/**
 * Проверка платежа по одному заказу и фоновый обход незакрытых заказов.
 *
 * Опрос из браузера покупателя (`http/routes-page.ts`, `/api/status/:token`)
 * и обход по таймеру (`startChecker` ниже) — два независимых пути к одному
 * и тому же заказу: покупатель может закрыть вкладку сразу после оплаты
 * (тогда только обход когда-нибудь заметит платёж), а может держать
 * вкладку открытой (тогда опрос замечает платёж раньше обхода). Оба вызывают
 * `checkOrder`, и оба могут увидеть подтверждённый платёж одновременно.
 * Аналог на PHP (`demo-shop/plugin/includes/OrderChecker.php` +
 * `OrderLock.php`) решает это локом в отдельной таблице WordPress — там
 * несколько PHP-процессов на одном сайте. Здесь сервер — один процесс
 * Node, поэтому блокировки в памяти процесса достаточно: два конкурентных
 * вызова `checkOrder` по одному и тому же заказу всё равно исполняются в
 * одном и том же процессе по очереди на каждом `await`.
 */
import type { PaymentStatus, Quote } from '@solanapaykz/core';
import type { Config } from './config.js';
import { decide, type Decision } from './decision.js';
import type { Order, Store } from './db.js';
import type { Log } from './log.js';
import { notifyTilda, type Отправка } from './tilda/notify.js';

/** Минимально нужный от SDK метод — не весь `SolanaPayKZ`, чтобы в тестах подменять без сети и RPC. */
export interface PaymentCheckerClient {
  checkPayment(params: { reference: string; quote: Quote }): Promise<PaymentStatus>;
}

export interface CheckerDeps {
  config: Config;
  store: Store;
  client: PaymentCheckerClient;
  log: Log;
  /** Только для тестов: подменяет реальную отправку HTTP внутри `notifyTilda`. */
  отправка?: Отправка;
  /** Только для тестов: паузы между попытками уведомления (см. `tilda/notify.ts`). */
  задержкиMs?: readonly number[];
}

/** Интервал фонового обхода — 60 секунд. */
const ИНТЕРВАЛ_ОБХОДА_MS = 60_000;

/** Не более 30 заказов за один проход обхода. */
const ЗАКАЗОВ_ЗА_ПРОХОД = 30;

/**
 * id заказов, которые сейчас проверяются. Общий для всех вызовов
 * `checkOrder` в процессе (опрос и обход используют одну и ту же карту) —
 * иначе опрос из вкладки покупателя и обход по таймеру могли бы пройти
 * проверку блокчейна параллельно и оба довести один и тот же заказ до
 * «оплачен», отправив два уведомления Tilda.
 */
const занятыеЗаказы = new Set<number>();

/**
 * Проверяет платёж по заказу и применяет решение к записи в базе.
 *
 * Ничего не делает, если заказ уже проверяется другим вызовом (см.
 * `занятыеЗаказы` выше), если его состояние не в белом списке (`decide`
 * решает это тоже, но здесь — раньше, чтобы не дёргать RPC по заказу,
 * который автоматика и так не тронет), или если сеть в настройках
 * разошлась с сетью заказа (ошибка конфигурации, не платёж).
 */
export async function checkOrder(order: Order, deps: CheckerDeps): Promise<Decision> {
  if (занятыеЗаказы.has(order.id)) {
    return { action: 'ждать', note: 'Заказ уже проверяется другим вызовом — эта проверка пропущена.' };
  }

  занятыеЗаказы.add(order.id);
  try {
    return await проверитьЗаблокированный(order, deps);
  } finally {
    занятыеЗаказы.delete(order.id);
  }
}

async function проверитьЗаблокированный(order: Order, deps: CheckerDeps): Promise<Decision> {
  // Перечитываем перед любым решением: пока заказ ждал своей очереди в
  // обходе (или пока опрос и обход спорили за лок выше), другой путь мог
  // уже закрыть его — работаем с последними данными, а не с теми, что были
  // на момент постановки в очередь.
  const свежий = deps.store.findByToken(order.token) ?? order;

  if (свежий.state !== 'ожидает' && свежий.state !== 'просрочен') {
    return {
      action: 'ждать',
      note: `Заказ в состоянии «${свежий.state}» — автоматика его не трогает.`,
    };
  }

  // Расхождение сети в настройках и в заказе — ошибка конфигурации
  // продавца (переключил сеть в настройках уже после создания заказа), а
  // не сигнал о платеже: адрес получателя валиден в обеих сетях Solana, и
  // запрос в чужую сеть нашёл бы там платёж с той же меткой — например,
  // бесплатный перевод в devnet, закрывающий mainnet-заказ как оплаченный.
  // Заказ не трогаем, как при сбое сети, но это требует внимания
  // администратора, а не повторной проверки, поэтому — отдельная запись в
  // журнал. Проверяется здесь, а не внутри SDK: `checkPayment` тоже это
  // умеет (сравнивает `quote.cluster` со своим кластером), но там это было
  // бы исключением, не заслуживающим доверия наравне со сбоем сети.
  if (свежий.cluster !== deps.config.cluster) {
    deps.log.warn(
      'Сеть в настройках не совпадает с сетью заказа — проверка невозможна, это ошибка конфигурации',
      {
        tildaOrderId: свежий.tildaOrderId,
        сетьНастроек: deps.config.cluster,
        сетьЗаказа: свежий.cluster,
      },
    );
    return {
      action: 'ждать',
      note: 'Сеть в настройках не совпадает с сетью заказа — обратитесь к администратору.',
    };
  }

  const quote = JSON.parse(свежий.quoteJson) as Quote;

  let status: PaymentStatus;
  try {
    status = await deps.client.checkPayment({ reference: свежий.reference, quote });
  } catch (е) {
    // Сбой сети или узла Solana — не ответ о платеже, а отсутствие ответа
    // вообще. Заказ не трогаем: молчание узла не должно ни подтверждать,
    // ни отменять его.
    deps.log.warn('Не удалось проверить оплату: узел Solana недоступен или ответил ошибкой', {
      tildaOrderId: свежий.tildaOrderId,
      сообщение: (е as Error).message,
    });
    return { action: 'ждать', note: 'Не удалось проверить оплату, попробуем ещё раз позже.' };
  }

  const решение = decide({
    status,
    orderState: свежий.state,
    expiresAt: свежий.expiresAt,
    createdAt: свежий.createdAt,
    lateWindowSeconds: deps.config.lateWindowSeconds,
    now: Math.floor(Date.now() / 1000),
  });

  применитьРешение(свежий, решение, deps);

  return решение;
}

/**
 * Переводит заказ в состояние, которое означает решение, и — для «оплачен» —
 * запускает уведомление Tilda (не дожидаясь его исхода, см. комментарий
 * внутри случая «оплачен»). Синхронная: единственная асинхронная часть,
 * уведомление, намеренно не дожидается здесь ничего.
 */
function применитьРешение(order: Order, решение: Decision, deps: CheckerDeps): void {
  switch (решение.action) {
    case 'ждать':
      return;

    case 'просрочен':
      deps.store.updateState(order.id, 'просрочен');
      return;

    case 'не сошлось':
      // Транзакция есть, но не сходится с заказом — это разбирает человек
      // (см. `decision.ts`), поэтому Tilda не уведомляем: подтверждать
      // оплату заказа транзакцией, которая ему не соответствует, нельзя.
      deps.store.updateState(order.id, 'не сошлось', { txSignature: решение.signature });
      return;

    case 'поздний':
      // Деньги уже у продавца, но цена, по которой их ждали, на момент
      // оплаты уже не действовала — курс мог уйти в любую сторону. Пометить
      // такой заказ оплаченным автоматически значит отобрать у продавца
      // решение, которое принадлежит ему: он видит транзакцию в списке (мы
      // её сохранили) и помечает заказ оплаченным в самой Tilda, если сумма
      // его устраивает. Деньги при этом никуда не теряются — они уже на
      // кошельке продавца в любом случае. Tilda не уведомляем автоматически
      // ровно по той же причине, по которой автоматика не трогает
      // «не сошлось»: здесь она ошибается дороже человека.
      deps.store.updateState(order.id, 'поздний', { txSignature: решение.signature });
      return;

    case 'оплачен': {
      deps.store.updateState(order.id, 'оплачен', { txSignature: решение.signature });

      // Уведомление Tilda — не дело и не время того, кто вызвал
      // checkOrder: опрос из вкладки покупателя должен ответить сразу
      // после того, как заказ помечен оплаченным, а не после того, как
      // Tilda подтвердит приём (это может занять почти полторы минуты —
      // пять попыток с паузами 1/5/15/60 секунд, см. `tilda/notify.ts`).
      // Обход по таймеру по той же причине не должен застревать на одном
      // заказе и откладывать проверку следующих 29 в очереди. Поэтому
      // отправка запускается, но не ожидается (`void` ниже, не `await`) —
      // найдено проверкой в настоящем браузере: без этого опрос реально
      // подвисал, пока Tilda не отвечала.
      //
      // Защита «один платёж — одно уведомление» от этого не страдает и
      // срабатывает ДО начала отправки, а не после её завершения:
      // `updateState(order.id, 'оплачен', ...)` двумя строками выше —
      // синхронная запись в SQLite, она уже случилась к моменту вызова
      // `notifyTilda` ниже. `decide()` не пускает состояние «оплачен» (как
      // и «уведомлён») в белый список — значит ЛЮБОЙ следующий вызов
      // `checkOrder` по этому заказу (конкурентный — как только снимется
      // лок в конце этой же функции, — или более поздний, из другого
      // опроса или обхода) сразу ответит «ждать» и не вызовет ни
      // `checkPayment`, ни `notifyTilda` повторно — даже если эта, первая,
      // отправка ещё не завершилась. Проверено тестом
      // (tests/checker.test.ts): вторая проверка не идёт дальше состояния,
      // даже пока первая отправка искусственно «висит».
      //
      // `notifyTilda` кладёт `order.txSignature` в поле `transaction` —
      // передаём не `order` как есть (в нём ещё старое значение, `null` до
      // первой оплаты), а копию с уже актуальными `state`/`txSignature`,
      // не перечитывая заново из базы: мы только что сами туда это
      // записали, значение уже известно.
      const оплаченный: Order = { ...order, state: 'оплачен', txSignature: решение.signature };

      void notifyTilda(оплаченный, {
        config: deps.config,
        store: deps.store,
        log: deps.log,
        // `exactOptionalPropertyTypes` не даёт передать `undefined` в
        // необязательное поле напрямую — спред пустого объекта вместо
        // явного `отправка: undefined`, когда деп не задан (в бою всегда).
        ...(deps.отправка ? { отправка: deps.отправка } : {}),
        ...(deps.задержкиMs ? { задержкиMs: deps.задержкиMs } : {}),
      })
        .then((доставлено) => {
          // Один платёж — одно уведомление: как только оно доставлено,
          // заказ переходит в «уведомлён» — на случай, если по каким-то
          // причинам заказ всё же попадёт на повторную проверку, `decide`
          // и это состояние не пустит в белый список. Если доставка не
          // удалась (`notifyTilda` вернула false, исчерпав попытки), заказ
          // остаётся «оплачен»: следующая проверка этого же заказа (опрос
          // или обход) запустит уведомление снова.
          if (доставлено) {
            deps.store.updateState(order.id, 'уведомлён');
          }
        })
        .catch((е: unknown) => {
          // `notifyTilda` по своему контракту сама ловит и сеть, и чужой
          // ответ (см. `tilda/notify.ts`) — сюда попал бы только сбой
          // самой записи в базу внутри неё. Не даём такому провалу уйти
          // необработанным исключением где-то в фоне процесса.
          deps.log.error('notifyTilda упала не по правилам своей же обработки ошибок', {
            tildaOrderId: order.tildaOrderId,
            сообщение: (е as Error).message,
          });
        });

      return;
    }
  }
}

export interface WalkDeps extends CheckerDeps {
  /**
   * Только для тестов: заменяет вызов `checkOrder` на эту функцию для
   * каждого отобранного заказа — позволяет проверить сам обход (порядок,
   * устойчивость к падению одного заказа) отдельно от логики проверки
   * платежа.
   */
  наЗаказ?: (order: Order) => void | Promise<void>;
}

/**
 * Один проход фонового обхода: берёт не более `ЗАКАЗОВ_ЗА_ПРОХОД`
 * незакрытых заказов (старые первыми) и проверяет каждый. Падение проверки
 * одного заказа не прерывает обход остальных — иначе единственный сбойный
 * заказ останавливал бы проверку всех, кто идёт за ним в очереди.
 */
export async function обходОдинРаз(deps: WalkDeps): Promise<void> {
  const заказы = deps.store.listPending(
    ЗАКАЗОВ_ЗА_ПРОХОД,
    deps.config.lateWindowSeconds,
    Math.floor(Date.now() / 1000),
  );

  for (const заказ of заказы) {
    try {
      if (deps.наЗаказ) {
        await deps.наЗаказ(заказ);
      } else {
        await checkOrder(заказ, deps);
      }
    } catch (е) {
      deps.log.error('Фоновая проверка заказа упала — обход продолжается остальными заказами', {
        tildaOrderId: заказ.tildaOrderId,
        сообщение: (е as Error).message,
      });
    }
  }
}

/**
 * Запускает периодический фоновый обход (раз в 60 секунд) и возвращает
 * функцию остановки.
 *
 * Таймер помечен `unref()`: сам по себе он не должен держать процесс
 * живым — ни в тестах, ни при штатном завершении сервера.
 */
export function startChecker(deps: WalkDeps): () => void {
  const таймер = setInterval(() => {
    void обходОдинРаз(deps).catch((е) => {
      deps.log.error('Фоновый обход заказов упал целиком', { сообщение: (е as Error).message });
    });
  }, ИНТЕРВАЛ_ОБХОДА_MS);

  таймер.unref?.();

  return () => clearInterval(таймер);
}
