/** Интервал фонового обхода — 60 секунд. */
const ИНТЕРВАЛ_ОБХОДА_MS = 60_000;
/** Не более 30 заказов за один проход обхода. */
const ЗАКАЗОВ_ЗА_ПРОХОД = 30;
/** Тайм-аут одной проверки платежа (`checkPayment`) — 30 секунд (найдено ревью). */
const ТАЙМАУТ_ПРОВЕРКИ_ПЛАТЕЖА_MS_ПО_УМОЛЧАНИЮ = 30_000;
/** Окно повторных попыток уведомления с момента оплаты — сутки (найдено ревью). */
const ОКНО_ПОВТОРА_УВЕДОМЛЕНИЯ_SECONDS_ПО_УМОЛЧАНИЮ = 86_400;
/**
 * Минимальный интервал между РЕАЛЬНЫМИ (не пропущенными) попытками
 * довезти уведомление одному и тому же заказу через `довезтиУведомление` —
 * тот же темп, что и у самого фонового обхода (60 c): чаще не имеет
 * смысла, Tilda не отвечает быстрее.
 *
 * Правка финального ревью: `GET /api/status/:token` — второй, помимо
 * фонового обхода, независимый триггер `checkOrder`, и он вызывается из
 * вкладки покупателя раз в 5 секунд (`public/checkout.js`), а не раз в
 * минуту. Без этого предела заказ с недоставленным уведомлением получал бы
 * НОВУЮ реальную попытку на КАЖДОМ таком опросе — до 17 280 запросов к
 * Tilda по одному заказу за сутки, что жжёт квоту платного узла у
 * действительно платящего продавца ради заказа, который Tilda и так не
 * подтверждает.
 *
 * Ограничение выведено из уже хранимых в базе данных, без нового столбца
 * под метку времени последней попытки: `order.paidAt` (момент оплаты) и
 * `order.notifyAttempts` (сколько попыток УЖЕ было — считает и полный
 * цикл первого уведомления, и каждую последующую одиночную) вместе задают
 * нижнюю границу «должно было пройти не меньше notifyAttempts × интервал
 * секунд с момента оплаты» (см. `следующаяПопыткаНеРаньше`). Эффект тот
 * же, что у явного таймера последней попытки, но без отдельного столбца
 * и миграции схемы.
 */
const МИНИМАЛЬНЫЙ_ИНТЕРВАЛ_ПОВТОРА_УВЕДОМЛЕНИЯ_SECONDS_ПО_УМОЛЧАНИЮ = 60;
/**
 * Потолок длительности одного прохода обхода — 2 минуты.
 *
 * Взято из своей же оценки худшего случая, которую попросило проверить
 * ревью: платный RPC-провайдер при исчерпании квоты не отвечает МЕДЛЕННО
 * одному заказу — он перестаёт отвечать ВСЕМ запросам разом, а тайм-аут
 * `checkPayment` (см. выше) — 30 секунд на заказ. Без этого предела
 * `ЗАКАЗОВ_ЗА_ПРОХОД` заказов, зависших одновременно, растянули бы один
 * проход на 30 × 30 c = 15 минут — покупатель, оплативший в это время,
 * узнал бы о подтверждении через четверть часа и, скорее всего, решил бы,
 * что оплата не прошла, и ушёл раньше. 2 минуты — с большим запасом над
 * интервалом обхода (60 c) и намного меньше тех пятнадцати минут.
 *
 * Проход, прерванный по этому пределу, ничего не теряет: необработанные
 * заказы остаются в базе как есть и просто попадут в следующий проход —
 * `listPending` всегда отдаёт старые первыми, так что оставшиеся не
 * обработанными сейчас окажутся первыми же в следующей выборке.
 */
const МАКСИМАЛЬНАЯ_ДЛИТЕЛЬНОСТЬ_ОБХОДА_MS_ПО_УМОЛЧАНИЮ = 120_000;
/**
 * Насколько шире окна повтора уведомления берём заказы в выборку обхода
 * (`listPending`) — не строго по границе.
 *
 * Найдено ревью: условие выборки («ещё в пределах окна») и условие ветки
 * записи об окончательном провале («уже вышли за окно», см.
 * `довезтиУведомление`) строго дополняли друг друга — значит заказ,
 * пересёкший границу окна, выпадал из выборки МОЛЧА, ни разу не дойдя до
 * записи в журнал. Ровно это и есть главное требование: продавец должен
 * узнать, что деньги получены, а Tilda о них не знает.
 *
 * Запас даёт заказу ровно один лишний шанс попасть в обход ПОСЛЕ
 * истечения окна повтора — там он застанет `now - paidAt > окно`, получит
 * запись в журнал, а с истечением уже и самого запаса выпадет из выборки
 * навсегда. Взято равным двум интервалам обхода — с запасом на случай,
 * если предыдущий проход занял время, близкое к своему пределу.
 */
const ЗАПАС_ВЫБОРКИ_ДЛЯ_ЗАПИСИ_О_ПРОВАЛЕ_SECONDS_ПО_УМОЛЧАНИЮ = (2 * ИНТЕРВАЛ_ОБХОДА_MS) / 1000;

/**
 * id заказов, которые сейчас проверяются — общий для всех вызовов
 * `checkOrder` в процессе, иначе опрос и обход могли бы одновременно
 * довести один заказ до «оплачен» и отправить два уведомления.
 */
const занятыеЗаказы = new Set<number>();

/**
 * id заказов, для которых прямо сейчас идёт отправка уведомления Tilda —
 * отдельно от `занятыеЗаказы`. Первое уведомление (`уведомитьИЗакрыть`)
 * запускается фоном и не держит `занятыеЗаказы`: `checkOrder` возвращается
 * сразу после записи «оплачен», а отправка ещё может идти. Без этой карты
 * повторный вызов `checkOrder` (опрос или обход), увидев «оплачен» с
 * `notifiedOk = 0`, попал бы в `довезтиУведомление` и запустил вторую
 * отправку параллельно первой, ещё не завершившейся.
 */
const уведомляемыеЗаказы = new Set<number>();

/** Проверяет платёж по заказу и применяет решение к записи в базе. */
export async function checkOrder(order: Order, deps: CheckerDeps): Promise<Decision> {
  if (занятыеЗаказы.has(order.id)) {
    return { action: 'ждать', note: 'Заказ уже проверяется другим вызовом — эта проверка пропущена.' };
  }

  занятыеЗаказы.add(order.id);
  try {
    return await проверитьЗаблокированный(order, deps);
  } finally {
    занятыеЗаказы.delete(order.id);
  }
}

async function проверитьЗаблокированный(order: Order, deps: CheckerDeps): Promise<Decision> {
  // Перечитываем перед любым решением: пока заказ ждал своей очереди
  // (обход) или лока (конкурентный вызов выше), другой путь мог уже
  // закрыть его.
  const свежий = deps.store.findByToken(order.token) ?? order;

  // Заказ уже оплачен, но Tilda ещё не подтвердила приём уведомления —
  // повторная попытка без повторной проверки блокчейна: платёж уже
  // подтверждён, перепроверять его снова незачем.
  if (свежий.state === 'оплачен' && свежий.notifiedOk === 0) {
    return довезтиУведомление(свежий, deps);
  }

  if (свежий.state !== 'ожидает' && свежий.state !== 'просрочен') {
    return { action: 'ждать', note: `Заказ в состоянии «${свежий.state}» — автоматика его не трогает.` };
  }

  // Расхождение сети или адреса получателя в настройках и в заказе —
  // ошибка конфигурации продавца (сеть или кошелёк сменили в настройках
  // уже после создания заказа), а не сигнал о платеже: и адрес, и сеть
  // валидны сами по себе, проверка просто ушла бы не туда.
  //
  // Правка финального ревью: раньше заказ оставался «как есть» (state не
  // менялся), то есть фактически навсегда застревал в «ожидает» — а
  // «ожидает» без ограничения по времени в listPending означало, что он
  // навсегда занимает место в выборке фонового обхода. Сценарий не
  // гипотетический: переключение сети devnet -> mainnet при выходе в бой
  // оставляет все накопленные тестовые заказы ровно в этом положении, и
  // фоновый обход умирает в день запуска, молча — платёж дальше
  // обнаруживается, только пока покупатель держит вкладку открытой.
  // Теперь заказ переводится в отдельное состояние «ошибка настроек» —
  // decide() его и так не видел (белый список — только «ожидает»/
  // «просрочен»), а `listPending` эту ветку не выбирает вовсе (см. db.ts):
  // заказ, которому проверка блокчейна всё равно не поможет, перестаёт
  // расходовать место в очереди обхода и ждёт человека явно, а не
  // притворяясь ожидающим оплату.
  if (свежий.cluster !== deps.config.cluster) {
    deps.log.warn(
      'Сеть в настройках не совпадает с сетью заказа — проверка невозможна, это ошибка конфигурации',
      { tildaOrderId: свежий.tildaOrderId, сетьНастроек: deps.config.cluster, сетьЗаказа: свежий.cluster },
    );
    deps.store.updateState(свежий.id, 'ошибка настроек');
    return {
      action: 'ждать',
      note: 'Сеть в настройках не совпадает с сетью заказа — обратитесь к администратору.',
    };
  }

  if (свежий.recipient !== deps.config.recipient) {
    deps.log.warn(
      'Адрес получателя в настройках не совпадает с адресом заказа — проверка невозможна, это ошибка конфигурации',
      { tildaOrderId: свежий.tildaOrderId, адресНастроек: deps.config.recipient, адресЗаказа: свежий.recipient },
    );
    deps.store.updateState(свежий.id, 'ошибка настроек');
    return {
      action: 'ждать',
      note: 'Адрес получателя в настройках не совпадает с адресом заказа — обратитесь к администратору.',
    };
  }

  const quote = JSON.parse(свежий.quoteJson) as Quote;

  let status: PaymentStatus;
  try {
    status = await сОграничениемВремени(
      deps.client.checkPayment({ reference: свежий.reference, quote }),
      deps.тест?.таймаутПроверкиПлатежаMs ?? ТАЙМАУТ_ПРОВЕРКИ_ПЛАТЕЖА_MS_ПО_УМОЛЧАНИЮ,
    );
  } catch (е) {
    // Сбой сети/узла — не ответ о платеже, а отсутствие ответа вообще.
    // Тайм-аут (см. сОграничениемВремени выше) сюда же: неотвечающий узел
    // не должен держать заказ заблокированным до перезапуска процесса —
    // гонка сдаётся сама, лок снимется как обычно.
    deps.log.warn('Не удалось проверить оплату: узел Solana недоступен, ответил ошибкой или не уложился в тайм-аут', {
      tildaOrderId: свежий.tildaOrderId,
      сообщение: (е as Error).message,
    });
    return { action: 'ждать', note: 'Не удалось проверить оплату, попробуем ещё раз позже.' };
  }

  const решение = decide({
    status,
    orderState: свежий.state,
    expiresAt: свежий.expiresAt,
    createdAt: свежий.createdAt,
    lateWindowSeconds: deps.config.lateWindowSeconds,
    now: Math.floor(Date.now() / 1000),
  });

  применитьРешение(свежий, решение, deps);

  return решение;
}

/**
 * Гонка `промис` с тайм-аутом `ms` — и снятие таймера, когда гонку
 * выиграл `промис`.
 *
 * Доказано ревью замером: без `clearTimeout` в `finally` процесс не мог
 * завершиться тридцать секунд даже после мгновенного ответа узла — жил
 * один незагашенный таймер на каждый вызов. В бою это была бы задержка
 * корректной остановки сервера до тридцати секунд и до трёх десятков
 * висящих таймеров с замыканиями на каждый проход обхода.
 */
async function сОграничениемВремени<T>(промис: Promise<T>, ms: number): Promise<T> {
  let таймер!: ReturnType<typeof setTimeout>;
  const истечение = new Promise<never>((_, reject) => {
    таймер = setTimeout(() => reject(new Error(`checkPayment не ответил за ${ms} мс`)), ms);
  });
  try {
    return await Promise.race([промис, истечение]);
  } finally {
    clearTimeout(таймер);
  }
}

/**
 * Переводит заказ в состояние, которое означает решение. Для «оплачен» —
 * ещё и запускает уведомление Tilda; для «оплачен», «не сошлось» и
 * «поздний» — письмо продавцу (см. заголовок файла: во всех трёх у
 * продавца есть что узнать и что решить; «просрочен» письма не шлёт —
 * такие заказы многочисленны и не требуют участия человека).
 */
function применитьРешение(order: Order, решение: Decision, deps: CheckerDeps): void {
  switch (решение.action) {
    case 'ждать':
      return;

    case 'просрочен':
      deps.store.updateState(order.id, 'просрочен');
      return;

    case 'не сошлось': {
      // Транзакция есть, но не сходится с заказом — разбирает человек
      // (см. `decision.ts`); Tilda не уведомляем: платёж, который не
      // соответствует заказу, нельзя подтверждать как его оплату.
      deps.store.updateState(order.id, 'не сошлось', { txSignature: решение.signature });
      const свежий: Order = { ...order, state: 'не сошлось', txSignature: решение.signature };
      отправитьПисьмоПродавцу(свежий, решение, deps);
      return;
    }

    case 'поздний': {
      // Курс мог уйти к моменту поздней оплаты — решение о зачёте
      // принадлежит продавцу (см. `decision.ts`), деньги уже у него в
      // любом случае. Tilda не уведомляем автоматически по той же
      // причине, что и «не сошлось»: здесь автоматика ошибается дороже
      // человека.
      deps.store.updateState(order.id, 'поздний', { txSignature: решение.signature });
      const свежий: Order = { ...order, state: 'поздний', txSignature: решение.signature };
      отправитьПисьмоПродавцу(свежий, решение, deps);
      return;
    }

    case 'оплачен': {
      const оплаченоВ = Math.floor(Date.now() / 1000);
      deps.store.updateState(order.id, 'оплачен', { txSignature: решение.signature, paidAt: оплаченоВ });

      // Уведомление запускается, но не ожидается: иначе опрос из вкладки
      // покупателя завис бы на время всех повторов `notifyTilda` (до
      // полутора минут), а обход застревал бы на этом заказе (найдено
      // проверкой в настоящем браузере). От повторного запуска, пока эта
      // отправка ещё не завершилась, защищает НЕ `decide()` — заказ
      // «оплачен» с `notifiedOk = 0` в белый список decide() и не должен
      // попадать, его перехватывает `довезтиУведомление` ещё раньше (см.
      // `проверитьЗаблокированный`) — а карта `уведомляемыеЗаказы` (см.
      // `уведомитьИЗакрыть` и `довезтиУведомление` ниже; проверено тестом
      // в tests/checker.test.ts).
      const оплаченный: Order = { ...order, state: 'оплачен', txSignature: решение.signature, paidAt: оплаченоВ };
      уведомитьИЗакрыть(оплаченный, deps);
      отправитьПисьмоПродавцу(оплаченный, решение, deps);
      return;
    }
  }
}

/**
 * Отправляет письмо продавцу о заказе, только что впервые переведённом в
 * одно из трёх состояний (см. `применитьРешение`) — не ожидается вызывающим
 * по той же причине, что и `notifyTilda` в `уведомитьИЗакрыть`: письмо не
 * должно задерживать ни ответ на опрос покупателя (`checkOrder` вызывается
 * и оттуда), ни обход остальных заказов. Неудача отправки уже обработана
 * внутри `sendMerchantMail` (журнал, `Store.recordMailOutcome`) — здесь
 * лишний `catch` только на случай, если сама функция нарушит свой контракт
 * и бросит исключение (тот же приём, что у `уведомитьИЗакрыть`).
 */
function отправитьПисьмоПродавцу(order: Order, решение: Decision, deps: CheckerDeps): void {
  void sendMerchantMail(order, решение, {
    config: deps.config,
    store: deps.store,
    log: deps.log,
    // `exactOptionalPropertyTypes` не даёт передать `undefined` явным
    // значением необязательного поля — спред пустого объекта, когда
    // тестового крюка нет (в бою всегда).
    ...(deps.тест?.отправкаПисьма ? { тест: { отправка: deps.тест.отправкаПисьма } } : {}),
  }).catch((е: unknown) => {
    deps.log.error('sendMerchantMail упала не по правилам своей же обработки ошибок', {
      tildaOrderId: order.tildaOrderId,
      сообщение: (е as Error).message,
    });
  });
}

/**
 * Отправляет уведомление свежего платежа полным циклом (см.
 * `NotifyCallOptions` в `tilda/notify.ts` — здесь без ограничения числа
 * попыток за вызов, вызов ничего не блокирует). Успех уже отражён в базе
 * атомарно: `notifyTilda` на успешной попытке переводит заказ и в
 * `notifiedOk = 1`, и в `state = 'уведомлён'` одной записью (см.
 * `markNotified` в `db.ts`) — отдельно выставлять состояние здесь не
 * нужно. Не ожидается вызывающим.
 */
function уведомитьИЗакрыть(order: Order, deps: CheckerDeps): void {
  уведомляемыеЗаказы.add(order.id);
  void notifyTilda(order, {
    config: deps.config,
    store: deps.store,
    log: deps.log,
    // `exactOptionalPropertyTypes` не даёт передать `undefined` явным
    // значением необязательного поля — спред пустого объекта, когда
    // тестового крюка нет (в бою всегда).
    ...(deps.тест ? { тест: deps.тест } : {}),
  })
    .catch((е: unknown) => {
      // `notifyTilda` по контракту сама ловит и сеть, и чужой ответ — сюда
      // попал бы только сбой записи в базу внутри неё.
      deps.log.error('notifyTilda упала не по правилам своей же обработки ошибок', {
        tildaOrderId: order.tildaOrderId,
        сообщение: (е as Error).message,
      });
    })
    .finally(() => {
      уведомляемыеЗаказы.delete(order.id);
    });
}

/**
 * Заказ уже оплачен, но ещё не уведомлён — довоз уведомления РОВНО ОДНОЙ
 * попыткой за вызов (`{ максимумПопыток: 1 }` в `notifyTilda`), а не
 * полным циклом. Расписание повторов при этом задаёт частота самого
 * обхода (раз в минуту, см. `startChecker`), а не цикл в памяти процесса
 * — переживает перезапуск процесса, чего цикл с паузами в памяти не
 * умеет. Заодно одна попытка вместо цикла с паузами до 131 секунды не
 * рискует сама перекрыть предел длительности прохода
 * (`МАКСИМАЛЬНАЯ_ДЛИТЕЛЬНОСТЬ_ОБХОДА_MS_ПО_УМОЛЧАНИЮ`, 2 минуты).
 *
 * Пропускает, если для этого заказа уже идёт отправка (см.
 * `уведомляемыеЗаказы`) — первое уведомление свежего платежа запускается
 * фоном и `занятыеЗаказы` к этому моменту уже снят, так что именно эта
 * карта не даёт второй попытке начаться параллельно первой, ещё не
 * завершившейся.
 *
 * Успех уже отражён в базе атомарно (см. `уведомитьИЗакрыть` выше) —
 * `доставлено` здесь нужен только для текста решения.
 */
async function довезтиУведомление(order: Order, deps: CheckerDeps): Promise<Decision> {
  if (уведомляемыеЗаказы.has(order.id)) {
    return { action: 'ждать', note: 'Уведомление уже отправляется другим вызовом — эта проверка пропущена.' };
  }

  const окно = deps.тест?.окноПовтораУведомленияSeconds ?? ОКНО_ПОВТОРА_УВЕДОМЛЕНИЯ_SECONDS_ПО_УМОЛЧАНИЮ;
  const now = Math.floor(Date.now() / 1000);

  if (order.paidAt === null || now - order.paidAt > окно) {
    // Обход отбирает заказы в этой ветке с небольшим запасом сверх окна
    // (см. `ЗАПАС_ВЫБОРКИ_ДЛЯ_ЗАПИСИ_О_ПРОВАЛЕ_SECONDS_ПО_УМОЛЧАНИЮ`) —
    // именно чтобы заказ, пересёкший границу окна, ещё раз дошёл сюда и
    // получил эту запись, а не выпал из выборки молча. После неё —
    // последняя автоматическая попытка: заказ выйдет и из более широкой
    // выборки, и дальше обход его уже не увидит. Деньги у продавца, а
    // Tilda об оплате не узнает без вмешательства человека.
    deps.log.error(
      'Не удалось уведомить Tilda об оплате за отведённое время — автоматические попытки прекращены',
      { tildaOrderId: order.tildaOrderId, notifyAttempts: order.notifyAttempts },
    );
    return { action: 'ждать', note: 'Уведомление Tilda не доставлено, требуется ручная проверка.' };
  }

  // Не даём опросу из вкладки покупателя (раз в 5 секунд) инициировать
  // РЕАЛЬНУЮ попытку чаще, чем раз в МИНИМАЛЬНЫЙ_ИНТЕРВАЛ_ПОВТОРА_
  // УВЕДОМЛЕНИЯ_SECONDS_ПО_УМОЛЧАНИЮ (см. комментарий у константы выше) —
  // без нового столбца под метку времени последней попытки: граница
  // растёт вместе с notifyAttempts, поэтому после каждой реальной попытки
  // следующая разрешена не раньше чем через тот же интервал, а не только
  // в момент оплаты.
  const минИнтервал =
    deps.тест?.минимальныйИнтервалПовтораУведомленияSeconds ??
    МИНИМАЛЬНЫЙ_ИНТЕРВАЛ_ПОВТОРА_УВЕДОМЛЕНИЯ_SECONDS_ПО_УМОЛЧАНИЮ;
  if (now < order.paidAt + order.notifyAttempts * минИнтервал) {
    return {
      action: 'ждать',
      note: 'Слишком рано для следующей попытки уведомления Tilda — попробуем ещё раз позже.',
    };
  }

  уведомляемыеЗаказы.add(order.id);
  let доставлено: boolean;
  try {
    доставлено = await notifyTilda(
      order,
      {
        config: deps.config,
        store: deps.store,
        log: deps.log,
        ...(deps.тест ? { тест: deps.тест } : {}),
      },
      { максимумПопыток: 1 },
    );
  } finally {
    уведомляемыеЗаказы.delete(order.id);
  }

  return {
    action: 'ждать',
    note: доставлено
      ? 'Уведомление Tilda доставлено повторной попыткой.'
      : 'Повторная попытка уведомить Tilda не удалась, попробуем ещё раз.',
  };
}

/**
 * Один проход фонового обхода: берёт не более `ЗАКАЗОВ_ЗА_ПРОХОД`
 * незакрытых заказов (старые первыми) и проверяет каждый. Падение проверки
 * одного заказа не прерывает обход остальных.
 *
 * Выборка берёт заказы «оплачен» с недоставленным уведомлением немного
 * шире окна повтора (см. `ЗАПАС_ВЫБОРКИ_ДЛЯ_ЗАПИСИ_О_ПРОВАЛЕ_SECONDS_ПО_УМОЛЧАНИЮ`)
 * — иначе граница окна здесь и граница «сдаться» в `довезтиУведомление`
 * совпадали бы день в день, и заказ выпадал бы из выборки молча, ни разу
 * не дойдя до записи об окончательном провале.
 *
 * Проход также обрывается по истечении `МАКСИМАЛЬНАЯ_ДЛИТЕЛЬНОСТЬ_ОБХОДА_MS_ПО_УМОЛЧАНИЮ`
 * — см. комментарий у константы: при разом зависшем RPC-узле проверка
 * каждого заказа может упереться в свой тайм-аут, и без предела проход
 * растянулся бы на непомерное время. Заказы, до которых очередь не
 * дошла, никуда не деваются — `listPending` в следующий раз снова отдаст
 * их первыми (старые первыми), просто очередь пойдёт медленнее.
 */
export async function обходОдинРаз(deps: CheckerDeps): Promise<void> {
  const окноПовтора = deps.тест?.окноПовтораУведомленияSeconds ?? ОКНО_ПОВТОРА_УВЕДОМЛЕНИЯ_SECONDS_ПО_УМОЛЧАНИЮ;
  const запасВыборки =
    deps.тест?.запасВыборкиДляЗаписиОПровалеSeconds ?? ЗАПАС_ВЫБОРКИ_ДЛЯ_ЗАПИСИ_О_ПРОВАЛЕ_SECONDS_ПО_УМОЛЧАНИЮ;

  const заказы = deps.store.listPending(
    ЗАКАЗОВ_ЗА_ПРОХОД,
    deps.config.lateWindowSeconds,
    окноПовтора + запасВыборки,
    Math.floor(Date.now() / 1000),
  );

  const дедлайн =
    Date.now() + (deps.тест?.максимальнаяДлительностьОбходаMs ?? МАКСИМАЛЬНАЯ_ДЛИТЕЛЬНОСТЬ_ОБХОДА_MS_ПО_УМОЛЧАНИЮ);

  for (let i = 0; i < заказы.length; i++) {
    if (Date.now() > дедлайн) {
      // Сигнал, что с узлом плохо: в норме проход укладывается в отведённое
      // время с большим запасом, и это предупреждение никогда не должно
      // появляться при здоровом RPC.
      deps.log.warn('Обход прерван по истечении отведённого времени — не все заказы проверены в этом проходе', {
        обработано: i,
        всего: заказы.length,
        осталось: заказы.length - i,
      });
      return;
    }

    const заказ = заказы[i]!;
    try {
      if (deps.тест?.наЗаказ) {
        await deps.тест.наЗаказ(заказ);
      } else {
        await checkOrder(заказ, deps);
      }
    } catch (е) {
      deps.log.error('Фоновая проверка заказа упала — обход продолжается остальными заказами', {
        tildaOrderId: заказ.tildaOrderId,
        сообщение: (е as Error).message,
      });
    }
  }
}

/**
 * Запускает периодический фоновый обход (раз в 60 секунд) и возвращает
 * функцию остановки. Таймер помечен `unref()` — сам по себе не держит
 * процесс живым.
 */
export function startChecker(deps: CheckerDeps): () => void {
  const таймер = setInterval(() => {
    void обходОдинРаз(deps).catch((е) => {
      deps.log.error('Фоновый обход заказов упал целиком', { сообщение: (е as Error).message });
    });
  }, ИНТЕРВАЛ_ОБХОДА_MS);

  таймер.unref?.();

  return () => clearInterval(таймер);
}
