  /** Потолок длительности одного прохода обхода, мс. По умолчанию см. `МАКСИМАЛЬНАЯ_ДЛИТЕЛЬНОСТЬ_ОБХОДА_MS_ПО_УМОЛЧАНИЮ`. */
  максимальнаяДлительностьОбходаMs?: number;
