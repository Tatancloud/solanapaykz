/** Источник курса. Возвращает, сколько тенге стоит один токен. */
interface RateSource
{
    /**
     * Полоса правдоподобия для курса доллара к тенге — общего для обоих
     * реализаций внутреннего звена расчёта (BinanceRateSource берёт его
     * напрямую как пару USDTKZT, SyntheticRateSource — как курс агрегатора
     * валют). Тенге торгуется к доллару в этом диапазоне уже много лет:
     * выход за границы означает, что источник поменял базовую пару или
     * вернул курс другого инструмента, а не то, что доллар подорожал вдвое
     * за минуту.
     *
     * Нижняя граница взята с запасом ниже реального диапазона: резервный
     * источник обновляется раз в сутки и обычно даёт значение примерно на
     * процент ниже биржевого — полоса не должна спотыкаться об это
     * привычное расхождение.
     */
    public const USD_KZT_MIN = '400';
    public const USD_KZT_MAX = '600';

    /** Короткое имя для записи в заказ — по нему разбирают спорные случаи. */
    public function get_name(): string;

    /** @return string Курс десятичной строкой. */
    public function get_kzt_per_token(string $token): string;
}
