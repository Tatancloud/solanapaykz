<?php

declare(strict_types=1);

use PHPUnit\Framework\TestCase;

/**
 * Проверяет, что среда пригодна для расчёта денег.
 *
 * Тест не формальный: без bcmath расчёт суммы к оплате молча теряет
 * точность на заказах дороже 92 233,72 ₸ — предел целых чисел PHP.
 */
final class SmokeTest extends TestCase
{
    public function test_расширение_bcmath_доступно(): void
    {
        self::assertTrue(extension_loaded('bcmath'), 'bcmath обязателен для расчёта сумм');
    }

    public function test_крупная_сумма_считается_без_потери_точности(): void
    {
        // 92 234 ₸ по курсу 459,60 — на единицу выше предела обычных целых PHP.
        // bcdiv округляет вниз; округление вверх в пользу продавца делает
        // отдельная функция, она появится вместе с модулем арифметики.
        $units = bcdiv('9223400000000000000', '45960000000', 0);
        self::assertSame('200683202', $units);

        // Та же операция в обычных целых переполняется и даёт float.
        $overflow = 9223400 * 1000000000000;
        self::assertTrue(is_float($overflow), 'обычные целые здесь обязаны переполниться');
    }
}
